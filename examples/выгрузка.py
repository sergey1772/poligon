#!/usr/bin/env python3
"""Выгрузка (закон v50, слово Суверена 28.09).

«Работать у себя, а на GitHub заливать изменения одним действием: раз в день
или когда критическая масса, чтобы не потерять, или чат рушится, или песочница
умирает.»

Значит: каждый коммит на GitHub НЕ пушим. Коммиты копятся локально (наш git —
рабочая копия и источник правды), а на сервер уходит ПАКЕТ по критерию:
  * критическая масса — не_залито ≥ ПОРОГ_КОММИТОВ;
  * конец дня — с последней заливки ≥ ПОРОГ_ЧАСОВ;
  * срочная нужда — причина свободным текстом (--срочно --почему «…»):
    «песочница умирает» — если Суверен так и сказал; шаблона по умолчанию нет.

Состояние пакета — 00_START/выгрузка_состояние.json (последний выгруженный
sha и время), история — 00_START/журнал_выгрузок.md. Токен живёт только в
окружении одного вызова (GITHUB_TOKEN) и НИКОГДА не пишется в файлы дома.

Сейф токена (заявка №1): значение живёт ВНЕ дома — файл с правами 600
(~/.спрут/токен.json); заливка берёт токен одной командой (аргумент →
GITHUB_TOKEN → сейф), значение не попадает ни в файлы дома, ни в вывод.
Якорь выгрузок (заявка №2): голова запечатывается на носитель вне дома
(~/.спрут/якорь_выгрузок.json) и переживает перезапуск; сверка ловит «откат
хвоста» и «развилку» — дом не публикует усечение.

Ротация секретов по аренде (v118, заявка №8, «ФАКТ»): срок → отзыв → новое
значение. Дробление на фотоны: одно действие за раз — аренда, ротация, отзыв,
обесценивание — каждое отдельным вызовом; ротация ставит надгробие старого отпечатка (в доме он
мёртв ТОТЧАС, сохранён лишь отпечаток), а снаружи ждёт отзыва в окне минут; кольцо
замкнуто: ротация → факт дома → шаг ритма «секрет» → боль просроченного окна →
отзыв Суверена → лечение.

CLI:
    python3 examples/выгрузка.py            # состояние пакета (без сети)
    python3 examples/выгрузка.py --залить   # залить пакет, если пора
    python3 examples/выгрузка.py --залить --срочно --почему "чат рушится"
    python3 examples/выгрузка.py --залить --сухо     # показать, что уйдёт
    python3 examples/выгрузка.py --сейф              # состояние сейфа токена
    python3 examples/выгрузка.py --сейф-положить     # GITHUB_TOKEN → сейф (600)
    python3 examples/выгрузка.py --сейф-отозвать     # стереть сейф
"""
from __future__ import annotations

import json
import os
import subprocess
import time
import sys
from datetime import datetime, timezone
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СОСТОЯНИЕ_ФАЙЛ = "00_START/выгрузка_состояние.json"
ЖУРНАЛ_ФАЙЛ = "00_START/журнал_выгрузок.md"
ПОРОГ_КОММИТОВ = 100    # слово Суверена 29.09: пакет терпит до 100 коммитов
ПОРОГ_ЧАСОВ = 24.0      # «раз в день, в конце дня»
ЗАГЛУШКА_ТОКЕНА = "***"
СЕЙФ_ФАЙЛ = ".спрут/токен.json"
ЯКОРЬ_ФАЙЛ = ".спрут/якорь_выгрузок.json"
ПРАВА_СЕЙФА = 0o600
СРОК_СЕЙФА_С = 90 * 24 * 3600.0
НАДГРОБИЯ_ФАЙЛ = ".спрут/надгробия_секретов.json"
ПОРОГ_РОТАЦИИ = 0.75      # мир: новое значение просим на 75 % срока (50–75 %)
ОКНО_ОТЗЫВА_МИН = 10.0    # минуты, за которые старое обязано быть отозвано снаружи


def _коммитов(n: int) -> str:
    """По-русски: 1 коммит, 2 коммита, 5 коммитов (дом следит за словом)."""
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} коммит"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return f"{n} коммита"
    return f"{n} коммитов"


def _git(дом: Path, *доводы: str) -> tuple[int, str]:
    и = subprocess.run(["git", *доводы], cwd=str(дом),
                       capture_output=True, text=True)
    return и.returncode, (и.stdout + и.stderr).strip()


def _читай(дом: Path) -> dict:
    п = дом / СОСТОЯНИЕ_ФАЙЛ
    if not п.exists():
        return {}
    try:
        return json.loads(п.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}


def _сколько_после(дом: Path, sha: str) -> int | None:
    """Коммитов после sha (None — sha неизвестен, например после переигрыша)."""
    код, вывод = _git(дом, "rev-list", "--count", f"{sha}..HEAD")
    return int(вывод) if код == 0 and вывод.isdigit() else None


def возраст_хвоста(дом: Path | None = None) -> float | None:
    """П-9 (RPO 48 ч): сколько часов САМОМУ СТАРОМУ незалитому коммиту.

    Зеркало — не «когда-нибудь»: работа, живущая только в песочнице дольше
    48 ч, — долг перед домом. Считаем по датам коммитов после origin/main.
    """
    дом = Path(дом or КОРЕНЬ)
    код, вывод = _git(дом, "log", "origin/main..HEAD", "--reverse",
                      "--format=%ct", "--max-count=1")
    if код != 0 or not вывод.strip().isdigit():
        return None
    старейший = datetime.fromtimestamp(int(вывод.strip()), tz=timezone.utc)
    return round((datetime.now(timezone.utc) - старейший).total_seconds() / 3600, 1)


def значение_сейфа(дом: Path | None = None) -> str:
    """Значение из сейфа для КЛАССИФИКАЦИИ (широкий/тонкий) — не для печати.

    Хвост 19.6: сам сейф читает только выгрузка; здесь нужен лишь признак
    формы ключа. Ошибка чтения — пустая строка (класс «неизвестный»).
    """
    try:
        п = сейф_путь(дом)
        if not п.is_file():
            return ""
        д = json.loads(п.read_text(encoding="utf-8"))
        return str(д.get("токен") or "")
    except Exception:                       # noqa: BLE001 — сейф чужой беде не причина
        return ""


def класс_секрета(значение: str) -> str:
    """П-10: широкий классический ключ (repo+workflow) или тонкий.

    Классический `ghp_…` даёт доступ ко ВСЕМУ репозиторию — долг замены на
    тонкий (fine-grained) виден ритму, а не живёт в чьей-то памяти.
    """
    з = str(значение or "")
    if з.startswith("ghp_"):
        return "классический"
    if з.startswith("github_pat_"):
        return "тонкий"
    return "неизвестный"


def состояние(дом: Path | None = None) -> dict:
    """Состояние пакета: что лежит невыгруженным и сколько ждём."""
    дом = Path(дом or КОРЕНЬ)
    код, ветка = _git(дом, "rev-parse", "--abbrev-ref", "HEAD")
    ветка = ветка if код == 0 else "?"
    код, голова = _git(дом, "rev-parse", "HEAD")
    голова = голова if код == 0 else "?"
    ст = _читай(дом)
    залит = ст.get("sha", "")
    когда = ст.get("когда")
    часов = None
    if когда:
        try:
            часов = round((datetime.now(timezone.utc)
                           - datetime.fromisoformat(когда)
                           ).total_seconds() / 3600, 1)
        except ValueError:
            часов = None
    # «первая выгрузка»: состояния нет вовсе — считаем все коммиты ветки
    if залит == "":
        код, всего = _git(дом, "rev-list", "--count", "HEAD")
        не_залито = int(всего) if код == 0 and всего.isdigit() else 0
        первая = True
    else:
        после = _сколько_после(дом, залит)
        не_залито = -1 if после is None else после
        первая = False
    хвост = возраст_хвоста(дом)
    секр = значение_сейфа(дом)
    return {"ветка": ветка, "голова": голова, "залит_sha": залит,
            "не_залито": не_залито, "первая": первая,
            "когда": когда, "часов": часов, "возраст_хвоста_ч": хвост,
            "класс_секрета": класс_секрета(секр),
            "порог_коммитов": ПОРОГ_КОММИТОВ, "порог_часов": ПОРОГ_ЧАСОВ}


def пора(с: dict, срочно: bool = False,
         почему: str = "") -> tuple[bool, str]:
    """Критерий закона v50: когда пакет идёт на GitHub. Срочность (v119, заявка
    №6) — не шаблон, а названная причина свободным текстом: «песочница умирает»
    годится, если Суверен так и сказал, но по умолчанию шаблона нет."""
    if с["не_залито"] == 0:
        return False, "нечего заливать — пакет пуст"
    if срочно:
        причина = str(почему or "").strip()
        if len(причина) < 10:
            return False, ("срочность без причины: срочная заливка обязана назвать "
                           "причину свободным текстом (--почему «…»), а не шаблоном")
        return True, f"срочная нужда: {причина}"
    if с["не_залито"] < 0:
        return True, "история переиграна — нужна выгрузка (sha неизвестен)"
    if с["первая"]:
        return True, "первая выгрузка"
    if с["не_залито"] >= с["порог_коммитов"]:
        return True, (f"критическая масса: {_коммитов(с['не_залито'])} "
                      f"(порог {с['порог_коммитов']})")
    if с["часов"] is not None and с["часов"] >= с["порог_часов"]:
        return True, f"конец дня: {с['часов']} ч с прошлой заливки"
    ждём = (f"{_коммитов(с['не_залито'])}, "
            + (f"{с['часов']} ч" if с["часов"] is not None else "ещё не заливали"))
    return False, f"ждём пакет: {ждём}"


def _внутри(путь: Path, дом: Path | None) -> bool:
    """Путь внутри дома (значения и якоря в доме не живут)."""
    if дом is None:
        return False
    д = Path(дом).resolve()
    п = Path(путь).resolve()
    return п == д or д in п.parents


def отпечаток(значение: str) -> str:
    import hashlib
    return hashlib.sha256(str(значение).encode("utf-8")).hexdigest()[:12]


def сейф_путь(дом: Path | None = None) -> Path:
    """Сейф токена — ВНЕ дома: значения не живут в репозитории.
    Для нашего дома — домашний каталог; для чужого (тестового) — рядом с ним,
    чтобы чужие дома не трогали наш сейф и не текли друг в друга."""
    дом = Path(дом or КОРЕНЬ).resolve()
    if дом == Path(КОРЕНЬ).resolve():
        return Path.home() / СЕЙФ_ФАЙЛ
    return дом.parent / ".спрут" / Path(СЕЙФ_ФАЙЛ).name


def якорь_путь(дом: Path | None = None) -> Path:
    """Носитель якоря — ВНЕ дома: якорь переживает перезапуск дома.
    Чужой дом держит свой носитель рядом с собой (изоляция тестов)."""
    дом = Path(дом or КОРЕНЬ).resolve()
    if дом == Path(КОРЕНЬ).resolve():
        return Path.home() / ЯКОРЬ_ФАЙЛ
    return дом.parent / ".спрут" / Path(ЯКОРЬ_ФАЙЛ).name


def токен_в_сейф(токен: str, *, путь: Path | None = None, дом: Path | None = None,
                 срок_с: float = СРОК_СЕЙФА_С, когда: float | None = None,
                 кто: str = "") -> dict:
    """Положить токен в сейф: файл 600 вне дома; наружу — отпечаток и срок."""
    токен = str(токен or "").strip()
    if not токен:
        raise ValueError("пустой токен в сейф не кладётся")
    п = Path(путь or сейф_путь(дом))
    if _внутри(п, дом):
        raise ValueError("сейф в доме — не сейф: значение должно жить вне дома")
    срок_с = float(срок_с)
    if срок_с <= 0:
        raise ValueError("срок должен быть положительным")
    когда = float(когда if когда is not None else time.time())
    п.parent.mkdir(parents=True, exist_ok=True)
    ос = отпечаток(токен)
    п.write_text(json.dumps({"токен": токен, "отпечаток": ос,
                             "срок_до": когда + срок_с, "когда": когда,
                             "кто": str(кто)}, ensure_ascii=False, indent=1) + "\n",
                 encoding="utf-8")
    os.chmod(п, ПРАВА_СЕЙФА)
    return {"отпечаток": ос, "срок_до": когда + срок_с}


def токен_из_сейфа(*, путь: Path | None = None, когда: float | None = None,
                   живость=None) -> dict:
    """Предъявление токена: по имени и в момент нужды; отказ называет причину."""
    п = Path(путь or сейф_путь())
    if not п.exists():
        return {"отказ": "нет сейфа"}
    права = п.stat().st_mode & 0o777
    поправлено = ""
    if права != ПРАВА_СЕЙФА:
        # Снапшот песочницы теряет права у НАШЕГО сейфа (известная ловушка 30.09).
        # Свой файл — свои права: чиним сами и говорим об этом; чужие не трогаем.
        import os as _os
        наш = п.stat().st_uid == _os.getuid() if hasattr(_os, "getuid") else False
        if not наш:
            return {"отказ": f"права не 600 ({oct(права)[-3:]}) — файл чужой"}
        try:
            _os.chmod(п, ПРАВА_СЕЙФА)
            поправлено = f"права поправлены ({oct(права)[-3:]}→600)"
        except OSError:
            return {"отказ": f"права не 600 ({oct(права)[-3:]}) и не поправились"}
    try:
        з = json.loads(п.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {"отказ": "сейф нечитаем"}
    когда = float(когда if когда is not None else time.time())
    срок_до = з.get("срок_до")
    if срок_до is not None and когда >= срок_до:
        return {"отказ": "истёк срок"}
    токен = str(з.get("токен", ""))
    if not токен:
        return {"отказ": "сейф пуст"}
    if живость is not None and not живость(токен):
        return {"отказ": "токен мёртв"}
    return {"токен": токен, "отпечаток": з.get("отпечаток", отпечаток(токен)),
            "осталось_с": None if срок_до is None else срок_до - когда,
            "кто": з.get("кто", ""), "поправлено": поправлено}


def сейф_отозвать(*, путь: Path | None = None, повод: str = "") -> dict:
    """Отзыв: сейф стирается целиком; повтор честно отвечает «сейфа нет»."""
    п = Path(путь or сейф_путь())
    if not п.exists():
        return {"отозван": False, "почему": "сейфа нет"}
    п.unlink()
    return {"отозван": True, "повод": str(повод)}


def сейф_состояние(*, путь: Path | None = None, когда: float | None = None) -> dict:
    """Состояние сейфа для CLI: без значения — путь, отпечаток, права, живёт ли."""
    п = Path(путь or сейф_путь())
    когда = float(когда if когда is not None else time.time())
    с = {"есть": п.exists(), "путь": str(п), "права": "", "отпечаток": "",
         "срок_до": None, "живёт": False, "осталось_с": None}
    if not с["есть"]:
        return с
    с["права"] = oct(п.stat().st_mode & 0o777)[-3:]
    try:
        з = json.loads(п.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return с
    срок_до = з.get("срок_до")
    с["отпечаток"] = з.get("отпечаток", "")
    с["срок_до"] = срок_до
    с["осталось_с"] = None if срок_до is None else срок_до - когда
    с["живёт"] = с["права"] == "600" and (срок_до is None or когда < срок_до)
    return с


# ―― Ротация секретов по аренде (v118, заявка №8) ――
def надгробия_путь(дом: Path | None = None) -> Path:
    """Надгробия обесцененных отпечатков — рядом с сейфом, вне дома."""
    дом = Path(дом or КОРЕНЬ).resolve()
    if дом == Path(КОРЕНЬ).resolve():
        return Path.home() / НАДГРОБИЯ_ФАЙЛ
    return дом.parent / ".спрут" / Path(НАДГРОБИЯ_ФАЙЛ).name


def _надгробия_читай(путь: Path) -> list:
    if not путь.exists():
        return []
    try:
        з = json.loads(путь.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
    return list(з.get("надгробия", []))


def _надгробия_пиши(путь: Path, надгробия: list) -> None:
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(json.dumps({"надгробия": надгробия}, ensure_ascii=False,
                               indent=1) + "\n", encoding="utf-8")
    try:
        os.chmod(путь, ПРАВА_СЕЙФА)
    except OSError:
        pass


def _полный_срок(путь: Path) -> float | None:
    """Срок аренды целиком: новый отпечаток живёт столько же, сколько прежний."""
    try:
        з = json.loads(путь.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError, FileNotFoundError):
        return None
    срок_до, когда = з.get("срок_до"), з.get("когда")
    return None if срок_до is None else float(срок_до) - float(когда or срок_до)


def _болит(дом: Path | None, ключ: str, что: str, улика: str = "") -> None:
    if дом is None:
        return
    try:
        from факты import боль, боли
        if not any(б["ключ"] == ключ for б in боли(дом)):
            боль(что, кто="секрет", дом=дом, цена_с=0.0, улика=улика, ключ=ключ)
    except (ImportError, RuntimeError, OSError):
        pass


def _лечи(дом: Path | None, ключ: str, чем: str) -> None:
    if дом is None:
        return
    try:
        from факты import залечить, боли
        if any(б["ключ"] == ключ for б in боли(дом)):
            залечить(ключ, чем=чем, дом=дом, кто="секрет")
    except (ImportError, RuntimeError, OSError):
        pass


def _факт_секрета(дом: Path | None, выбор: str, улика: str, поля: dict) -> None:
    if дом is None:
        return
    try:
        from факты import записать_факт
        записать_факт(дом, {
            "задача": f"секрет: {выбор} — ротация по аренде (срок → отзыв → новое)",
            "выбор": выбор,
            "из": ["ротировано", "отозвано", "обесценено"],
            "кто": "секрет", "цена_с": 0.0,
            "обоснование": "утечка старого значения должна быть бесполезна "
                           "за минуты (заявка №8)",
            "улика": улика, "секрет": поля,
        })
    except (ImportError, RuntimeError, OSError):
        pass


def секрет_аренда(*, путь: Path | None = None, дом: Path | None = None,
                  когда: float | None = None) -> dict:
    """Аренда секрета: живёт ли, сколько осталось, пора ли ротировать (75 %)."""
    п = Path(путь or сейф_путь(дом))
    когда = float(когда if когда is not None else time.time())
    итог = {"есть": False, "отпечаток": "", "срок_до": None, "осталось_с": None,
            "доля_срока": 0.0, "пора_ротации": False, "просрочен": False}
    if not п.exists():
        return итог
    try:
        з = json.loads(п.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return итог
    срок_до, начало = з.get("срок_до"), float(з.get("когда", когда))
    итог.update({"есть": bool(з.get("токен")),
                 "отпечаток": з.get("отпечаток", "")})
    if срок_до is None:
        return итог
    срок_до = float(срок_до)
    всего = срок_до - начало
    доля = 0.0 if всего <= 0 else max(0.0, min(1.0, (когда - начало) / всего))
    итог.update({"срок_до": срок_до, "осталось_с": срок_до - когда,
                 "доля_срока": доля, "пора_ротации": доля >= ПОРОГ_РОТАЦИИ,
                 "просрочен": когда >= срок_до})
    return итог


def ротировать(новое: str, *, путь: Path | None = None, дом: Path | None = None,
               когда: float | None = None, повод: str = "по сроку",
               окно_мин: float = ОКНО_ОТЗЫВА_МИН, срок_с: float | None = None,
               кто: str = "Суверен") -> dict:
    """Ротация: новое значение принято, старое мертво В ДОМЕ тотчас, а снаружи
    ждёт отзыва в окне минут; просроченное окно — улика «секрет:отзыв»."""
    новое = str(новое or "").strip()
    if not новое:
        raise ValueError("пустое новое значение: ротация не из воздуха")
    окно_мин = float(окно_мин)
    if окно_мин < 0:
        raise ValueError("окно отзыва отрицательным не бывает")
    когда = float(когда if когда is not None else time.time())
    п = Path(путь or сейф_путь(дом))
    прежнее = сейф_состояние(путь=п, когда=когда)
    нп = надгробия_путь(дом)
    надгробия = _надгробия_читай(нп)
    живая = bool(прежнее["есть"] and прежнее["отпечаток"])
    прежний = прежнее["отпечаток"] or (надгробия[-1]["отпечаток"] if надгробия else "")
    if not прежний:
        raise ValueError("ротировать нечего: ни аренды, ни обесцененного отпечатка")
    срок_с = float(срок_с) if срок_с is not None else (_полный_срок(п) or СРОК_СЕЙФА_С)
    if живая:
        долг_до = None if окно_мин <= 0 else когда + окно_мин * 60.0
        надгробия.append({"отпечаток": прежний, "обесценен": True,
                          "обесценен_когда": когда, "долг_до": долг_до,
                          "повод": повод, "кто": кто, "закрыт": None})
        _надгробия_пиши(нп, надгробия)
    else:
        долг_до = None          # прежний уже обесценен: окно дважды не открываем
    з = токен_в_сейф(новое, путь=п, дом=дом, когда=когда, срок_с=срок_с, кто=кто)
    _факт_секрета(дом, "ротировано",
                  f"старый отпечаток {прежний} обесценен; долг отзыва до {долг_до}",
                  {"отпечаток_старого": прежний,
                   "отпечаток_нового": з["отпечаток"], "долг_до": долг_до,
                   "повод": повод, "окно_мин": окно_мин})
    _лечи(дом, "секрет:утечка", "новое значение принято после обесценивания")
    _лечи(дом, "секрет:срок", "аренда свежая")
    _сверить_долги(дом, нп, когда)
    return {"отпечаток_старого": прежний,
            "отпечаток_нового": з["отпечаток"], "долг_до": долг_до,
            "мёртв_в_доме": True, "повод": повод, "окно_мин": окно_мин}


def _сверить_долги(дом: Path | None, путь_н: Path, когда: float) -> list:
    """Долги отзыва старше окна — улика «секрет:отзыв», а не тишина."""
    просрочено = [н for н in _надгробия_читай(путь_н)
                  if н.get("закрыт") is None and н.get("долг_до") is not None
                  and когда > float(н["долг_до"])]
    if просрочено:
        _болит(дом, "секрет:отзыв",
               f"старый отпечаток не отозван: {просрочено[0]['отпечаток']}",
               улика=f"окно истекло {когда - float(просрочено[0]['долг_до']):.0f} с назад")
    return просрочено


def отозван(отпечаток: str, *, дом: Path | None = None,
            когда: float | None = None, кто: str = "Суверен") -> dict:
    """Суверен отозвал старый отпечаток снаружи: долг закрыт, улика лечится."""
    отпечаток = str(отпечаток).strip()
    когда = float(когда if когда is not None else time.time())
    нп = надгробия_путь(дом)
    надгробия = _надгробия_читай(нп)
    цель = next((н for н in надгробия if н.get("отпечаток") == отпечаток
                 and н.get("закрыт") is None), None)
    if цель is None:
        return {"закрыт": False, "почему": "долга нет: отпечаток не ждёт отзыва"}
    цель["закрыт"] = когда
    цель["закрыл"] = str(кто)
    _надгробия_пиши(нп, надгробия)
    остались = _сверить_долги(дом, нп, когда)
    if not остались:
        _лечи(дом, "секрет:отзыв", f"{кто} отозвал старый отпечаток")
    _факт_секрета(дом, "отозвано",
                  f"{кто} отозвал отпечаток {отпечаток}",
                  {"отпечаток": отпечаток, "закрыт": когда, "кто": кто})
    return {"закрыт": True, "отпечаток": отпечаток, "когда": когда}


def обесценить(повод: str, *, путь: Path | None = None, дом: Path | None = None,
               когда: float | None = None, кто: str = "Суверен") -> dict:
    """Утечка/подозрение: секрет обесценивается ТОТЧАС, без окна (окно — 0)."""
    повод = str(повод or "").strip()
    if not повод:
        raise ValueError("обесценивание без повода — брак: назови причину")
    когда = float(когда if когда is not None else time.time())
    п = Path(путь or сейф_путь(дом))
    с = сейф_состояние(путь=п, когда=когда)
    стёрт = False
    if п.exists():
        п.unlink()
        стёрт = True
    нп = надгробия_путь(дом)
    надгробия = _надгробия_читай(нп)
    if с["отпечаток"]:
        надгробия.append({"отпечаток": с["отпечаток"], "обесценен": True,
                          "обесценен_когда": когда, "долг_до": когда,
                          "повод": f"обесценен: {повод}", "кто": кто,
                          "закрыт": None})
        _надгробия_пиши(нп, надгробия)
    _болит(дом, "секрет:утечка", f"секрет обесценен: {повод}",
           улика=f"сейф стёрт {'да' if стёрт else 'нет'}")
    _факт_секрета(дом, "обесценено", f"повод: {повод}",
                  {"отпечаток": с["отпечаток"], "повод": повод, "окно_мин": 0})
    _сверить_долги(дом, нп, когда)
    return {"сейф_стёрт": стёрт, "окно_мин": 0, "повод": повод,
            "отпечаток": с["отпечаток"]}


def секрет_состояние(*, путь: Path | None = None, дом: Path | None = None,
                     когда: float | None = None) -> dict:
    """Состояние аренды и надгробий; просроченные долги кричат болью канала."""
    когда = float(когда if когда is not None else time.time())
    ар = секрет_аренда(путь=путь, дом=дом, когда=когда)
    нп = надгробия_путь(дом)
    надгробия = _надгробия_читай(нп)
    долги = [н for н in надгробия if н.get("закрыт") is None]
    просрочено = _сверить_долги(дом, нп, когда)
    if ар["просрочен"]:
        _болит(дом, "секрет:срок",
               "аренда секрета просрочена — ротация обязательна",
               улика=f"срок был {ар['срок_до']}")
    else:
        _лечи(дом, "секрет:срок", "аренда свежая")
    if not просрочено:
        _лечи(дом, "секрет:отзыв", "долгов отзыва нет")
    требует = ""
    if not ар["есть"]:
        требует = "новое значение"
    elif ар["просрочен"] or ар["пора_ротации"]:
        требует = "ротация"
    return {"аренда": ар, "надгробия": надгробия, "долгов": len(долги),
            "просроченных": len(просрочено), "требует": требует,
            "класс_секрета": класс_секрета(значение_сейфа(дом))}


def живость_github(токен: str, время_с: float = 6.0) -> bool | None:
    """Живость токена по API GitHub: True/False; None — не проверить (нет сети)."""
    import urllib.error
    import urllib.request
    з = urllib.request.Request("https://api.github.com/user",
                               headers={"Authorization": f"Bearer {токен}",
                                        "User-Agent": "spurt-dom"})
    try:
        with urllib.request.urlopen(з, timeout=время_с) as о:
            return 200 <= о.status < 300
    except urllib.error.HTTPError as е:
        return False if е.code == 401 else None
    except Exception:
        return None


def высота(дом: Path) -> int | None:
    """Высота истории = число коммитов до головы (номер якоря выгрузки)."""
    код, вывод = _git(дом, "rev-list", "--count", "HEAD")
    return int(вывод) if код == 0 and вывод.isdigit() else None


def якорь_читай(*, носитель: Path | None = None) -> list:
    п = Path(носитель or якорь_путь())
    if not п.exists():
        return []
    try:
        з = json.loads(п.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
    return list(з.get("якоря", []))


def якорь_запомнить(номер: int, голова: str, *, носитель: Path | None = None,
                    дом: Path | None = None, когда: float | None = None,
                    кто: str = "") -> dict:
    """Запечатать голову на носитель вне дома; усечение не публикуется."""
    номер, голова = int(номер), str(голова)
    п = Path(носитель or якорь_путь(дом))
    if _внутри(п, дом):
        raise ValueError("носитель в доме — не носитель: якорь живёт вне дома")
    прежние = якорь_читай(носитель=п)
    последний = max(прежние, key=lambda я: я["номер"]) if прежние else None
    if последний is not None and номер < последний["номер"]:
        raise ValueError("дом не публикует усечение: номер меньше прежнего")
    когда = float(когда if когда is not None else time.time())
    я = {"номер": номер, "голова": голова, "печать": отпечаток(голова),
         "когда": когда, "кто": str(кто)}
    п.parent.mkdir(parents=True, exist_ok=True)
    п.write_text(json.dumps({"якоря": прежние + [я]}, ensure_ascii=False,
                            indent=1) + "\n", encoding="utf-8")
    try:
        os.chmod(п, ПРАВА_СЕЙФА)
    except OSError:
        pass
    return я


def якорь_сверить(номер: int, голова: str, *, носитель: Path | None = None,
                  дом: Path | None = None) -> dict:
    """Сверка головы с якорем: откат хвоста и развилка — улики, рост — согласие."""
    номер, голова = int(номер), str(голова)
    прежние = якорь_читай(носитель=носитель or якорь_путь(дом))
    if not прежние:
        return {"согласовано": True, "улика": "", "почему": "первый якорь"}
    последний = max(прежние, key=lambda я: я["номер"])
    итог = {"согласовано": True, "улика": "", "номер": номер,
            "прежний": {"номер": последний["номер"], "печать": последний["печать"]}}
    if номер < последний["номер"]:
        итог.update({"согласовано": False, "улика": "откат хвоста"})
    elif номер == последний["номер"] and голова != последний["голова"]:
        итог.update({"согласовано": False, "улика": "развилка"})
    return итог


def объявить_заливку(дом: Path, голова: str, не_залито: int,
                     почему: str = "", кто: str = "выгрузка") -> dict:
    """Заливка — измерение (v112, Волна 5): настоящий push оставляет факт
    с хэшем головы и числом коммитов; ответ CI — второе ребро триады."""
