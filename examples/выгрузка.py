def _записать_журнал(дом: Path, голова: str, не_залито: int, почему: str,
                     метка: str) -> None:
    ж = дом / ЖУРНАЛ_ФАЙЛ
    ж.parent.mkdir(parents=True, exist_ok=True)
    if not ж.exists():
        ж.write_text("# Журнал выгрузок (закон v50: пакетом, не по коммиту)\n",
                     encoding="utf-8")
    with ж.open("a", encoding="utf-8") as д:
        д.write(f"- {datetime.now():%d.%m.%Y %H:%M} · {метка} · {голова[:7]} · "
                f"коммитов {не_залито} · {почему}\n")


