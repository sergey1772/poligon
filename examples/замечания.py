"""Замечания (Статья 61): мелкая тонкость, замеченная на практике.

Замечание — не дефект и не урок: это слабый сигнал. Оно дешевле урока и ловится
раньше. Механизм ведёт НЕПРЕРЫВНЫЙ ЖУРНАЛ (append-only), взвешивает замечания,
даёт каждому действие и поднимает повторы до уроков и статей.

Законы, обеспеченные этим кодом:
    61.1 Замечание — тонкость из практики, не озвученная ранее; замечать —
         дело каждого: и человека, и агента. Слово Суверена — замечание
         высшего веса.
    61.2 Замечено — записано. Незаписанное замечание теряется; затишье —
         красный флаг, а не чистота (мировой опыт: «ноль рапортов месяцами —
         культурный сигнал беды»).
    61.3 Замечание обязано нести УЛИКУ (место, где видно): без улики это
         мнение, а не замечание.
    61.4 Замечание обязано получить ДЕЙСТВИЕ (клетка, урок, статья или долг);
         замечание без действия — украшение (мировой опыт: «чёрная дыра
         рапортов» учит, что рапорт ничего не меняет).
    61.5 Повтор по одной ткани ОБЯЗАН подниматься: третье замечание по ткани —
         не замечание, а урок или статья (мировой опыт: консолидация
         наблюдений требует явного триггера).
    61.6 Отложенное замечание ОБЯЗАНО быть названо с причиной: склад — не
         свалка; висяк дольше 48 часов краснит.
    61.7 У замечания есть ЛУПА (чем замечено) и ВЕС 1..5; вес растёт с
         повтором — тихие повторы громче одиночного крика.

Источники:
    * Safety science: near-miss как опережающий признак, «report black hole»,
      «zero reports — red flag», разбор первопричин без поиска виновного
      (ifactoryapp.com 2026; safetyevolution 2026; MDPI Sustainability 11/5/1264).
    * Память агентов: Generative Agents — append-only журнал наблюдений с весом
      важности и рефлексией, синтезирующей наблюдения в обобщения; без
      рефлексии поведение вырождается (memx.app 2026; arXiv 2603.07670).
      Reflexion: память — не лог, а урок. Voyager: библиотека навыков 15,3×.

MODE: product
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

# Дом держит вещи по именам: журнал живёт в 42_УРОКИ/замечания.jsonl,
# читаемая тень — 42_УРОКИ/замечания.md (названы явно, чтобы не быть сиротами).
КОРЕНЬ = Path(__file__).parent.parent
ЖУРНАЛ = Path("42_УРОКИ") / "замечания.jsonl"
ЧИТАЕМОЕ = Path("42_УРОКИ") / "замечания.md"

СТАТУСЫ = ("замечено", "назначено", "внедрено", "отложено", "закрыто")
ВИДЫ_ДЕЙСТВИЯ = ("клетка", "урок", "статья", "долг")
ЛУПЫ = {
    "тишина": "чего НЕ произошло: молчание контура, ноль находок, ноль докладов",
    "повтор": "то же самое уже было: тихий повтор говорит громче одиночного крика",
    "несоответствие": "слово и дело разошлись: имя не то, мера не та, статус не тот",
    "терпимое": "мелочь, которую все видят и терпят: живёт дольше, чем заслужила",
    "лишнее": "тяжесть без пользы: то, что можно снять и никто не заметит",
    "хрупкое": "держится на честном слове: сломается от первого толчка",
}
ШКАЛА = {1: "мелочь", 2: "стоит помнить", 3: "стоит действия", 4: "стоит урока",
         5: "стоит закона"}
ПОРОГ_ВИСЯКА_Ч = 48
ПОРОГ_ЗАТИШЬЯ_ДН = 7
ПОРОГ_ЭСКАЛАЦИИ = 3          # третье замечание по ткани — пора обобщать


class Замечание(Exception):
    """Отказ механизма: замечание без улики или действие без замечания."""


def _сегодня() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _путь(дом: Path | None = None, файл: Path | None = None) -> Path:
    return файл or (Path(дом or КОРЕНЬ) / ЖУРНАЛ)


def прочитать(дом: Path | None = None) -> list[dict]:
    """Журнал замечаний (append-only; пустой файл — не ошибка)."""
    п = _путь(дом)
    if not п.exists():
        return []
    записи: list[dict] = []
    for строка in п.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка:
            continue
        try:
            з = json.loads(строка)
        except json.JSONDecodeError:
            continue                      # битая строка не роняет журнал (У-253)
        if isinstance(з, dict) and з.get("номер"):
            записи.append(з)
    return записи


def _записать(дом: Path, записи: list[dict]) -> None:
    п = _путь(дом)
    п.parent.mkdir(parents=True, exist_ok=True)
    вр = п.with_suffix(".jsonl.tmp")
    вр.write_text("\n".join(json.dumps(з, ensure_ascii=False) for з in записи) + "\n",
                  encoding="utf-8")
    вр.replace(п)
    _рендер(дом, записи)


def _рендер(дом: Path, записи: list[dict]) -> None:
    """Читаемая тень журнала (производное): глазами видно, что где лежит."""
    строки = ["# Замечания дома",
              "",
              "Мелкие тонкости, замеченные на практике. Каждое обязано получить",
              "действие: клетку, урок, статью или долг (Статья 61).",
              ""]
    for з in записи:
        строки.append(
            f"**З-{з['номер']} · {з['ткань']} · {ШКАЛА.get(з['вес'], '?')} · "
            f"{з['статус']}** — {з['текст']}")
        строки.append(f"  лупа: {з.get('лупа', '?')} · улика: {з.get('улика', '?')} · "
                      f"кто: {з.get('кто', '?')} · когда: {з.get('когда', '?')}")
        if з.get("действие"):
            строки.append(f"  действие: {з['действие']}"
                          + (f" → {з['куда']}" if з.get("куда") else ""))
        if з.get("причина"):
            строки.append(f"  отложено: {з['причина']}")
        строки.append("")
    (Path(дом) / ЧИТАЕМОЕ).write_text("\n".join(строки), encoding="utf-8")


def взвесить(лупа: str, повтор: int = 1, от_суверена: bool = False) -> int:
    """Вес 1..5: лупа задаёт основу, повтор поднимает, слово Суверена — вверх."""
    основа = {"тишина": 3, "повтор": 2, "несоответствие": 3, "терпимое": 4,
              "лишнее": 2, "хрупкое": 4}.get(лупа, 2)
    вес = основа + min(2, max(0, повтор - 1))
    if от_суверена:
        вес += 1
    return max(1, min(5, вес))


def заметить(дом: Path | None = None, текст: str = "", ткань: str = "",
             улика: str = "", лупа: str = "терпимое", кто: str = "агент",
             откуда: str = "практика") -> dict:
    """Замечено — записано (61.2). Без улики не принимается (61.3)."""
    дом = Path(дом or КОРЕНЬ)
    текст, ткань, улика = текст.strip(), ткань.strip(), улика.strip()
    if not текст:
        raise Замечание("пустое замечание: текст обязателен")
    if not улика:
        raise Замечание("без улики это мнение, а не замечание (61.3): "
                        "укажи место, где видно")
    if лупа not in ЛУПЫ:
        raise Замечание(f"неизвестная лупа «{лупа}»: {', '.join(ЛУПЫ)}")
    записи = прочитать(дом)
    повтор = 1 + sum(1 for з in записи if з.get("ткань") == ткань)
    вес = взвесить(лупа, повтор, от_суверена=кто.lower().startswith("суверен"))
    з = {"номер": len(записи) + 1, "когда": _сегодня(), "кто": кто,
         "откуда": откуда, "текст": текст, "ткань": ткань, "лупа": лупа,
         "улика": улика, "вес": вес, "повтор": повтор, "статус": "замечено",
         "действие": "", "куда": "", "причина": ""}
    записи.append(з)
    _записать(дом, записи)
    return з


def _найти(записи: list[dict], номер: int) -> dict:
    з = next((х for х in записи if int(х["номер"]) == int(номер)), None)
    if з is None:
        raise Замечание(f"замечания З-{номер} нет в журнале")
    return з


def назначить(дом: Path | None = None, номер: int = 0, действие: str = "",
              вид: str = "клетка") -> dict:
    """Действие обязано быть названо видом: клетка, урок, статья или долг."""
    if вид not in ВИДЫ_ДЕЙСТВИЯ:
        raise Замечание(f"вид действия «{вид}» вне списка {ВИДЫ_ДЕЙСТВИЯ}")
    дом = Path(дом or КОРЕНЬ)
    записи = прочитать(дом)
    з = _найти(записи, номер)
    if not действие.strip():
        raise Замечание("действие обязано быть названо (61.4)")
    з["действие"], з["вид"], з["статус"] = действие.strip(), вид, "назначено"
    _записать(дом, записи)
    return з


def внедрить(дом: Path | None = None, номер: int = 0, куда: str = "") -> dict:
    """Внедрено: назови место, куда замечание легло (клетка/урок/статья/долг)."""
    дом = Path(дом or КОРЕНЬ)
    записи = прочитать(дом)
    з = _найти(записи, номер)
    if not куда.strip():
        raise Замечание("внедрение обязано быть названо местом (61.4)")
    з["куда"], з["статус"] = куда.strip(), "внедрено"
    _записать(дом, записи)
    return з


def отложить(дом: Path | None = None, номер: int = 0, причина: str = "") -> dict:
    """Отложено с причиной: склад — не свалка (61.6)."""
    дом = Path(дом or КОРЕНЬ)
    записи = прочитать(дом)
    з = _найти(записи, номер)
    if not причина.strip():
        raise Замечание("отложенное обязано быть названо с причиной (61.6)")
    з["причина"], з["статус"] = причина.strip(), "отложено"
    _записать(дом, записи)
    return з


def закрыть(дом: Path | None = None, номер: int = 0) -> dict:
    """Закрыть можно только внедрённое или отложенное с причиной (fail-closed)."""
    дом = Path(дом or КОРЕНЬ)
    записи = прочитать(дом)
    з = _найти(записи, номер)
    if з["статус"] not in ("внедрено", "отложено"):
        raise Замечание("закрыть можно только внедрённое или отложенное "
                        "с причиной (61.4): замечание без действия — украшение")
    з["статус"] = "закрыто"
    _записать(дом, записи)
    return з


def _часы(с) -> float:
    try:
        к = datetime.fromisoformat(str(с))
    except ValueError:
        return 0.0
    return (datetime.now() - к).total_seconds() / 3600.0


def эскалации(дом: Path | None = None) -> list[dict]:
    """61.5: повторы по одной ткани — пора обобщать в урок или статью."""
    записи = прочитать(дом)
    ткани: dict[str, list[dict]] = {}
    for з in записи:
        ткани.setdefault(з.get("ткань", "?"), []).append(з)
    итог = []
    for ткань, зс in ткани.items():
        внедрено = sum(1 for з in зс if з["статус"] in ("внедрено", "закрыто"))
        if len(зс) >= ПОРОГ_ЭСКАЛАЦИИ and внедрено < len(зс):
            итог.append({"ткань": ткань, "замечаний": len(зс),
                         "внедрено": внедрено, "вес": max(з["вес"] for з in зс),
                         "почему": f"ткань «{ткань}» повторилась {len(зс)} раза — "
                                   f"это уже не замечание, а урок или статья"})
    return sorted(итог, key=lambda х: -х["замечаний"])


def свод(дом: Path | None = None) -> dict:
    """Свод: доля внедрения, висяки, затишье, эскалации (61.2, 61.5, 61.6)."""
    записи = прочитать(дом)
    внедрено = sum(1 for з in записи if з["статус"] in ("внедрено", "закрыто"))
    ждут = [з for з in записи if з["статус"] in ("замечено", "назначено")]
    висяки = [з for з in ждут if _часы(з.get("когда", "")) > ПОРОГ_ВИСЯКА_Ч]
    затишье = round(_часы(записи[-1]["когда"]) / 24.0, 1) if записи else 0.0
    доля = round(100.0 * внедрено / len(записи)) if записи else 0
    вердикт = "зелёный"
    почему = "каждое замечание движется к действию"
    if записи and затишье > ПОРОГ_ЗАТИШЬЯ_ДН:
        вердикт, почему = "РОСТ", (f"затишье {затишье} сут — ноль замечаний "
                                   f"это красный флаг, а не чистота (61.2)")
    if висяки:
        вердикт = "КРАСНЫЙ"
        почему = (f"висяков {len(висяки)}: замечание без действия дольше "
                  f"{ПОРОГ_ВИСЯКА_Ч}ч — украшение (61.4)")
    return {"замечаний": len(записи), "внедрено": внедрено, "доля_внедрения": доля,
            "ждут": len(ждут), "висяков": len(висяки), "затишье_сут": затишье,
            "эскалации": эскалации(дом), "вердикт": вердикт, "почему": почему}


def шаг_ритма(дом: Path | None = None) -> tuple[bool, str]:
    """Шаг ритма: замечания без действия и затишье — сигнал в общий ход."""
    с = свод(дом)
    if с["вердикт"] == "зелёный":
        return True, (f"замечаний {с['замечаний']} · внедрено {с['внедрено']} "
                      f"({с['доля_внедрения']}%) · висяков 0")
    return False, f"{с['вердикт']}: {с['почему']}"


КЛЮЧИ = ("--заметить", "--ткань", "--улика", "--лупа", "--кто", "--откуда",
         "--назначить", "--действие", "--вид",
         "--внедрить", "--куда",
         "--отложить", "--причина",
         "--закрыть", "--эскалации")


def главное(аргументы: list[str] | None = None) -> int:
    import sys
    арг = аргументы if аргументы is not None else sys.argv[1:]
    дом = Path(арг[0]).resolve() if арг and not арг[0].startswith("--") else КОРЕНЬ
    чужие = [д for д in арг if д.startswith("--") and д not in КЛЮЧИ]
    if чужие:                      # У-259: имя флага — контракт
        print(f"нет такого ключа: {' '.join(чужие)} — знаю {', '.join(КЛЮЧИ)}; "
              "молчаливый фолбэк запрещён (У-259)")
        return 2

    def _значение(ключ: str, по_умолчанию: str = "") -> str:
        if ключ not in арг:                  # необязательный ключ — не падение
            return по_умолчанию
        и = арг.index(ключ)
        return арг[и + 1] if и + 1 < len(арг) else по_умолчанию

    if "--лупа" in арг and "--заметить" not in арг:
        for имя, смысл in ЛУПЫ.items():
            print(f"  {имя}: {смысл}")
        return 0
    if "--заметить" in арг:
        try:
            з = заметить(дом, текст=_значение("--заметить"),
                         ткань=_значение("--ткань", "без ткани"),
                         улика=_значение("--улика"),
                         лупа=_значение("--лупа", "терпимое"),
                         кто=_значение("--кто", "агент"),
                         откуда=_значение("--откуда", "практика"))
        except Замечание as е:
            print(f"ОТКАЗ: {е}")
            return 1
        print(f"ЗАМЕЧЕНО З-{з['номер']}: {ШКАЛА[з['вес']]} · ткань «{з['ткань']}» · "
              f"повтор {з['повтор']} · лупа «{з['лупа']}»"
              + (f" → эскалация: пора обобщать ({з['повтор']} по ткани)"
                 if з["повтор"] >= ПОРОГ_ЭСКАЛАЦИИ else ""))
        return 0
    if "--внедрить" in арг:
        з = внедрить(дом, номер=int(_значение("--внедрить")),
                     куда=_значение("--куда"))
        print(f"ВНЕДРЕНО З-{з['номер']}: {з['куда']}")
        return 0
    if "--назначить" in арг:
        з = назначить(дом, номер=int(_значение("--назначить")),
                      действие=_значение("--действие"),
                      вид=_значение("--вид", "клетка"))
        print(f"НАЗНАЧЕНО З-{з['номер']}: {з['вид']} — {з['действие']}")
        return 0
    if "--отложить" in арг:
        з = отложить(дом, номер=int(_значение("--отложить")),
                     причина=_значение("--причина"))
        print(f"ОТЛОЖЕНО З-{з['номер']}: {з['причина']}")
        return 0
    if "--закрыть" in арг:
        з = закрыть(дом, номер=int(_значение("--закрыть")))
        print(f"ЗАКРЫТО З-{з['номер']}")
        return 0
    if "--эскалации" in арг:
        э = эскалации(дом)
        if not э:
            print("ЭСКАЛАЦИЙ НЕТ: повторов по тканям ниже порога")
        for х in э:
            print(f"  ткань «{х['ткань']}»: {х['замечаний']} замечаний · "
                  f"внедрено {х['внедрено']} · {х['почему']}")
        return 0
    с = свод(дом)
    print(f"ЗАМЕЧАНИЯ: {с['вердикт']} · {с['почему']}")
    print(f"  замечаний {с['замечаний']} · внедрено {с['внедрено']} "
          f"({с['доля_внедрения']}%) · ждут {с['ждут']} · висяков {с['висяков']} · "
          f"затишье {с['затишье_сут']} сут")
    for х in с["эскалации"]:
        print(f"  ⚠ {х['почему']}")
    return 0 if с["вердикт"] == "зелёный" else 1


if __name__ == "__main__":
    raise SystemExit(главное())
