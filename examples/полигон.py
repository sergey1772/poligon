def попытки_части(предел: int, потолок: int | None = None) -> tuple[int, int]:
    """Две попытки части, СУММА которых ≤ потолка вызова (закон Фотонности).

    Было (45, 30) — 75с стены на одну часть: именно так 01.10 родились
    вмерзания «полигон-фотон 5/7». Теперь 30+15=45 при потолке 45.
    """
    п = int(потолок or ПРЕДЕЛ_ВЫЗОВА_С)
    первая = max(10, min(int(предел), п - 10))
    вторая = min(первая, max(5, п - первая))     # пересдача НЕ длиннее первой
    return (первая, вторая)

