def измерить_времена(дом: Path, xml: Path, когда: str | None = None) -> dict:
    """Фактические времена тест-файлов из JUnit XML прогона → время_тестов.json.
    Мера вместо сида (v164): после каждого фотона очередь строится по правде."""
    import xml.etree.ElementTree as ET
    замеры: dict[str, float] = {}
    тесты_замеры: dict[str, float] = {}
    try:
        корень = ET.parse(xml).getroot()
    except Exception as беда:      # битый XML не смеет ломать прогон
        return {"файлов": 0, "всего_с": 0.0, "файл": None, "беда": str(беда)}
    for тест in корень.iter("testcase"):
        # красный/сломанный прогон — НЕ мера (v165: глыба с ошибками записала
        # файлу 2,3 с вместо 130 с; планировщик счёл его лёгким, слипал глыбу
        # из 17 файлов и вмерзал — «процессы падают»)
        if any(тест.find(тег) is not None for тег in ("failure", "error")):
            continue
        класс = тест.get("classname") or ""
        имя = Path(тест.get("file") or (класс.split(".")[-1] + ".py")).name
        try:
            сек = float(тест.get("time") or 0.0)
        except ValueError:
            сек = 0.0
        замеры[имя] = round(замеры.get(имя, 0.0) + сек, 3)
        # v165: профиль ТЕСТОВ — тяжёлый файл дробится внутри, а не глыбой
        узел = f"{имя}::{тест.get('name')}"
        if "::" in класс:            # класс: examples.тесты_м::Класс
            узел = f"{имя}::{класс.split('::', 1)[1]}::{тест.get('name')}"
        тесты_замеры[узел] = round(тесты_замеры.get(узел, 0.0) + сек, 3)
    цель = Path(дом) / ИЗМЕРЕНИЕ_ФАЙЛ
    прежние: dict[str, float] = {}
    прежние_тесты: dict[str, float] = {}
    if цель.exists():               # мерж: фотон не стирает замеры соседей
        try:
            было = json.loads(цель.read_text(encoding="utf-8"))
            прежние = {и: float(с) for и, с in было.get("файлы", {}).items()
                       if isinstance(с, (int, float))}
            прежние_тесты = {и: float(с) for и, с in было.get("тесты", {}).items()
                             if isinstance(с, (int, float))}
        except Exception:
            прежние, прежние_тесты = {}, {}
    прежние.update(замеры)
    прежние_тесты.update(тесты_замеры)
    # файловая мера не смеет быть ниже суммы своих узлов: одиночный мусорный
    # замер (2,3 с у 130-секундного файла) вводил планировщик в обман
    файлы_узлов = {у.split("::")[0] for у in прежние_тесты}
    for имя in файлы_узлов:
        сумма = round(sum(с for у, с in прежние_тесты.items()
                          if у.startswith(имя + "::")), 3)
        прежние[имя] = round(max(прежние.get(имя, 0.0), сумма), 3)
    данные = {"комментарий": "измерено прогоном (v164): обновляется из JUnit XML",
              "когда": когда or datetime.now().isoformat(timespec="seconds"),
              "источник": Path(xml).name,
              "файлы": {и: прежние[и] for и in sorted(прежние)},
              "тесты": {и: прежние_тесты[и] for и in sorted(прежние_тесты)}}
    цель.parent.mkdir(parents=True, exist_ok=True)
    цель.write_text(json.dumps(данные, ensure_ascii=False, indent=1),
                    encoding="utf-8")
    return {"файлов": len(замеры), "всего_с": round(sum(замеры.values()), 1),
            "в_файле": len(данные["файлы"]), "тестов": len(данные["тесты"]),
            "файл": str(цель), "когда": данные["когда"]}


def отметить_оценку(дом: Path, файлы: list[str], сек: float) -> int:
    """Оценка-минимум файлам, чья часть таймаутнула (замера нет): впредь
    очередь дробит их отдельными частями (урок 30.09: три файла в одной
    части — таймаут; тесты_метазавода один идёт 103 с)."""
    цель = Path(дом) / ИЗМЕРЕНИЕ_ФАЙЛ
    данные: dict = {}
    if цель.exists():
        try:
            данные = dict(json.loads(цель.read_text(encoding="utf-8"))
                          .get("файлы", {}))
        except Exception:
            данные = {}
    изменено = 0
    for ф in файлы:
        было = float(данные.get(ф, 0.0) or 0.0)
        if сек > было:
            данные[ф] = round(float(сек), 3)
            изменено += 1
    if not изменено:
        return 0
    цель.parent.mkdir(parents=True, exist_ok=True)
    цель.write_text(json.dumps(
        {"комментарий": "измерено прогоном (v164): обновляется из JUnit XML",
         "когда": datetime.now().isoformat(timespec="seconds"),
         "источник": "оценка при таймауте части",
         "файлы": {и: данные[и] for и in sorted(данные)}},
        ensure_ascii=False, indent=1), encoding="utf-8")
    return изменено


def узлы_файла(дом: Path, имя: str, кэш: dict | None = None,
               предел_с: int = 120) -> list[str]:
    """Список тестов файла (узлы «файл::тест») через pytest --collect-only.
    Нужен, чтобы дробить тяжёлый файл ВНУТРИ (вариант «файл глыбой» — это
    ровно то, из-за чего песочница ложится). Кэш — в мере (ключ «узлы»)."""
    дом = Path(дом)
    if кэш is not None and имя in кэш:
        return list(кэш[имя])
    х = дом / "examples"
    try:
        р = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q",
                            "-p", "no:cacheprovider", str(х / имя)],
                           cwd=х, capture_output=True, text=True, timeout=предел_с)
        вывод = (р.stdout or "") + (р.stderr or "")
    except subprocess.TimeoutExpired:
        return []
    узлы: list[str] = []
    for строка in вывод.splitlines():
        строка = строка.strip()
        if "::" not in строка or строка.startswith("<"):
            continue
        часть = строка.split("::")
        файл = Path(часть[0]).name
        if файл != имя:
            continue
        узлы.append(файл + "::" + "::".join(часть[1:]))
    return sorted(set(узлы))


