def _сторож():
    import сторож_песочницы
    return сторож_песочницы


def бюджет(дом: Path | None = None) -> int:
    """Бюджет части — у сторожа песочницы (мера, а не константа), но не выше
    жёсткого предела Статьи 56."""
    return int(min(_сторож().бюджет_части(дом or КОРЕНЬ), ПРЕДЕЛ_ВЫЗОВА_С))


def план(дом: Path | None = None, бюджет_с: int | None = None,
         дробить_до_узлов: set[str] | None = None) -> list[dict]:
    """План частей: та же мера, что у боя (измеренные времена, тяжёлые файлы
    дробятся по узлам)."""
    return заход_план(дом or КОРЕНЬ, бюджет_с=бюджет_с or бюджет(дом),
                             дробить_до_узлов=дробить_до_узлов)


def загрузить(дом: Path | None = None) -> dict:
    п = (дом or КОРЕНЬ) / ЖУРНАЛ
    if п.exists():
        try:
            д = json.loads(п.read_text(encoding="utf-8"))
            д.setdefault("части", [])
            return д
        except Exception:
            pass
    return {"начат": "", "бюджет_с": 0, "состояние": "нет", "части": []}


def _сохранить(дом: Path, ж: dict) -> None:
    п = Path(дом) / ЖУРНАЛ
    п.parent.mkdir(parents=True, exist_ok=True)
    вр = п.with_suffix(".tmp")
    вр.write_text(json.dumps(ж, ensure_ascii=False, indent=1), encoding="utf-8")
    вр.replace(п)                     # атомарно: обрыв не рвёт журнал


def начать(дом: Path | None = None, бюджет_с: int | None = None) -> dict:
    дом = Path(дом) if дом else КОРЕНЬ
    б = int(бюджет_с or бюджет(дом))
    ж = {"начат": datetime.now().isoformat(timespec="seconds"), "бюджет_с": б,
         "состояние": "идёт", "части": план(дом, б)}
    _сохранить(дом, ж)
    return ж


def следующая(ж: dict) -> dict | None:
    for ч in ж.get("части", []):
        if ч.get("статус") in ("ждёт", "вмерзла"):
            return ч
    return None


def _падения_из_xml(xml: Path) -> list[str]:
    """Имена упавших тестов из JUnit XML — улика вскрытия."""
    import xml.etree.ElementTree as ET
    итог: list[str] = []
    try:
        корень = ET.parse(xml).getroot()
    except Exception:
        return итог
    for т in корень.iter("testcase"):
        if any(т.find(тег) is not None for тег in ("failure", "error")):
            файл = Path(т.get("file") or (т.get("classname", "").split(".")[-1]
                                          + ".py")).name
            итог.append(f"{файл}::{т.get('name')}")
    return итог


def _сайдкар(куда: Path | str, номер: int, ч: dict, *, хвост: str,
             секунды: float, падений: list[str]) -> None:
    """Улика части для CI: одна строка JSON на часть (номер, имя, файлы, время,
    статус, хвост, упавшие). Пишется и на прогоне, и на идемпотентном пропуске —
    иначе сводка судит неполный набор и «зелёное» врёт."""
    к = Path(куда)
    к.mkdir(parents=True, exist_ok=True)
    (к / f"часть{номер}.json").write_text(json.dumps({
        "part": номер, "name": ч.get("имя", ""), "files": ч.get("файлы", []),
        "sec": round(float(секунды), 2), "status": _статус_ci(ч.get("статус", "")),
        "tail": хвост, "failed": list(падений or [])},
        ensure_ascii=False, indent=1), encoding="utf-8")


def предел_части(ч: dict, дом: Path | None = None,
                 предел_с: int | None = None) -> int:
    """Предел одной части: план+20, но не выше закона Фотонности (45 с).

    Улика 01.10: формула «бюджет+20» резала часть до 40 с при CI-бюджете 20,
    а часть с планом 29.1 с бежала на раннере 57 с и убивалась колпаком 50.
    План частей обязан быть короче — предел не смеет быть у́же закона.
    """
    секунд = int(ч.get("секунд", 30) or 30)
    return int(min(предел_с or секунд + 20, ПРЕДЕЛ_ВЫЗОВА_С)) or ПРЕДЕЛ_ВЫЗОВА_С


def часть(дом: Path | None = None, номер: int = 1,
          предел_с: int | None = None,
          куда: Path | None = None) -> tuple[bool, str, float]:
    """Одна часть за один вызов: pytest по её единицам, ≤45 с. Результат —
    в журнал (обрыв процесса не теряет сделанного)."""
    дом = Path(дом) if дом else КОРЕНЬ
    ж = загрузить(дом)
    ч = next((х for х in ж["части"] if х["номер"] == номер), None)
    if ч is None:
        return (False, f"части {номер} нет в плане", 0.0)
    if ч.get("статус") == "ок":                    # идемпотентно: без прогона
        if куда is not None:                      # в CI и пропуск оставляет улику
            _сайдкар(куда, номер, ч, хвост=str(ч.get("хвост") or "ок"),
                     секунды=0.0, падений=[])
        return (True, f"из журнала: {ч.get('хвост') or 'ок'}", 0.0)
    предел = предел_части(ч, дом, предел_с)
    х = дом / "examples"
    папка = Path(tempfile.mkdtemp(prefix="полигон-"))
    xml = папка / f"часть{номер}.xml"
    команда = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
               f"--basetemp={папка / 'bt'}", f"--junit-xml={xml}"]
    for узел in ч["файлы"]:
        имя_файла, _, тест = узел.partition("::")
        команда.append(str(х / имя_файла) + (f"::{тест}" if тест else ""))
    t0 = time.perf_counter()
    код, вывод = -1, ""
    # Закон Фотонности: СУММА попыток обязана улечься в ПРЕДЕЛ_ВЫЗОВА_С.
    # Было 45+30=75с стены на одну часть — отсюда «полигон-фотон 5/7» в списке
    # вмерзаний 01.10 (сторож: 8 вмерзаний, 2 свежих). Мера: 30+15=45.
    for попытка, предел_попытки in enumerate(попытки_части(предел)):
        try:
            р = subprocess.run(команда, cwd=х, capture_output=True, text=True,
                               timeout=предел_попытки)
            код, вывод = р.returncode, (р.stdout or "") + (р.stderr or "")
            break
        except subprocess.TimeoutExpired:
            код = -1
            вывод = (f"ТАЙМАУТ >{предел_попытки}с"
                     + (" (пересдача после заморозки)" if попытка else ""))
    секунды = round(time.perf_counter() - t0, 1)
    if xml.exists():
        измерить_времена(дом, xml)          # мера обновляется прогоном
    улики = _падения_из_xml(xml)
    # Суд дрожи (как в бою): красное может быть дрожью, а не дефектом. Повтор
    # ровно упавших узлов — ОДИН раз; зелёный повтор = часть закрыта, а дрожь
    # названа в журнале (иначе полигон краснит дом по случайности).
    дрожь: list[str] = []
    if код != 0 and улики:
        повтор = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
                  f"--basetemp={папка / 'bt2'}"]
        for у in улики:
            имя_ф, _, тест = у.partition("::")
            повтор.append(str(х / имя_ф) + (f"::{тест}" if тест else ""))
        try:
            р2 = subprocess.run(повтор, cwd=х, capture_output=True, text=True,
                                timeout=min(30, предел))
            if р2.returncode == 0:
                дрожь = list(улики)
                код = 0
                вывод = (р2.stdout or "") + (р2.stderr or "")
        except subprocess.TimeoutExpired:
            pass
    if куда is not None and xml.exists():
        Path(куда).mkdir(parents=True, exist_ok=True)
        shutil.copy2(xml, Path(куда) / f"часть{номер}.xml")
    shutil.rmtree(папка, ignore_errors=True)
    строки = вывод.strip().splitlines()
    хвост = (строки[-1][:90] if строки else "пусто")
    if дрожь:
        хвост = (f"дрожь снята повтором ({len(дрожь)} узлов: "
                 f"{', '.join(д[:40] for д in дрожь[:2])})")
    if код == -1:
        ч["статус"] = "вмерзла"                    # не «провал»: дробить мельче
        _сторож().вмерзание(дом, ч["имя"], секунды, предел, вид="полигон")
        # план хвоста пересобирается мельче: вмерзшие файлы дробятся до узлов
        вмерзли = {str(ф).split("::")[0] for ф in ч["файлы"]}
        готовые = {ф for х2 in ж["части"] if х2.get("статус") == "ок"
                   for ф in х2["файлы"]}
        хвост_части = [ч] + [х2 for х2 in ж["части"] if х2["номер"] > номер]
        новые = план(дом, дробить_до_узлов=вмерзли)
        плоские = [е for ч2 in новые for е in ч2["файлы"]]
        плоские = [е for е in плоские if е not in готовые]
        пересобранные = _нарезать(дом, плоские)
        ж["части"] = [х2 for х2 in ж["части"] if х2["номер"] < номер]
        ж["части"] += [ч]
        for н, новая in enumerate(пересобранные, номер + 1):
            новая["номер"] = н
            новая["имя"] = f"полигон-фотон {н}/{номер + len(пересобранные)}"
            ж["части"].append(новая)
        _ = хвост_части
    else:
        ч["статус"] = "ок" if код == 0 else "провал"
    ч["хвост"] = хвост
    ч["время_с"] = секунды
    ч["падений"] = [] if дрожь else улики
    ч["дрожь"] = дрожь
    ч["когда"] = datetime.now().isoformat(timespec="seconds")
    if куда is not None:                 # CI: сайдкар части — улика артефактом
        _сайдкар(куда, номер, ч, хвост=хвост, секунды=секунды,
                 падений=ч["падений"])
    все_закрыты = all(х2.get("статус") in ("ок", "провал")
                      for х2 in ж["части"])
    if все_закрыты:
        ж["состояние"] = ("готов" if all(х2.get("статус") == "ок"
                                         for х2 in ж["части"]) else "красный")
        ж["закрыт"] = datetime.now().isoformat(timespec="seconds")
    _сохранить(дом, ж)
    if код != 0:
        вскрытие(дом)                              # автопсия сразу, не «потом»
    return (код == 0, хвост, секунды)


def _нарезать(дом: Path, единицы: list[str]) -> list[dict]:
    """Нарезка хвоста по бюджету (для пересборки после вмерзания)."""
    б = бюджет(дом)
    оценки = dict(_оценки_единиц(дом, единицы))
    крупные = sorted(((е, оценки.get(е, 15.0)) for е in единицы),
                     key=lambda п: (-п[1], п[0]))
    части: list[list[str]] = []
    текущая: list[str] = []
    сумма = 0.0
    for е, с in крупные:
        if текущая and сумма + с > б:
            части.append(текущая)
            текущая, сумма = [], 0.0
        текущая.append(е)
        сумма += с
    if текущая:
        части.append(текущая)
    всего = len(части)
    итог = []
    for н, пачка in enumerate(части, 1):
        итог.append({"номер": н, "имя": f"полигон-фотон {н}/{всего}",
                     "файлы": пачка,
                     "секунд": round(sum(оценки.get(е, 15.0) for е in пачка), 1),
                     "единиц": len(пачка), "статус": "ждёт", "хвост": ""})
    return итог


def стоп(дом: Path | None = None, почему: str = "") -> dict:
    """Мягкая остановка фона: стоп-файл, а не убийство процесса — цикл сам
    закончит текущую часть и выйдет (журнал цел)."""
    дом = Path(дом) if дом else КОРЕНЬ
    п = дом / СТОП
    п.write_text(почему or datetime.now().isoformat(timespec="seconds"),
                 encoding="utf-8")
    return {"стоп": str(п)}


def снять_стоп(дом: Path | None = None) -> bool:
    п = (дом or КОРЕНЬ) / СТОП
    if п.exists():
        п.unlink()
        return True
    return False


def _фон_активен(дом: Path) -> int | None:
    п = дом / ПИД
    if not п.exists():
        return None
    try:
        пид = int(п.read_text(encoding="utf-8").strip().split()[0])
    except Exception:
        return None
    try:
        os.kill(пид, 0)
        return пид
    except OSError:
        return None


def цикл(дом: Path | None = None, минут: float = 30.0,
         пауза_с: float = 1.0) -> dict:
    """Фоновый цикл: шаг за шагом, пока план не закрыт, время не вышло или не
    появился стоп-файл. Каждый шаг — одна часть ≤45 с (Фотонность)."""
    дом = Path(дом) if дом else КОРЕНЬ
    предел = time.time() + минут * 60
    шагов = 0
    while time.time() < предел:
        if (дом / СТОП).exists():
            _журнал_строка(дом, "стоп-файл: цикл завершён по слову/знаку")
            break
        ж = загрузить(дом)
        if ж.get("состояние") in ("готов", "красный"):
            _журнал_строка(дом, f"план закрыт: {ж['состояние']}")
            break
        ч = следующая(ж)
        if ч is None:
            _журнал_строка(дом, "незакрытых частей нет")
            break
        ок, хвост, сек = часть(дом, ч["номер"])
        шагов += 1
        _журнал_строка(дом, f"часть {ч['номер']}: {'✅' if ок else '❌'} "
                            f"{сек}с · {хвост}")
        if not ок and ч["статус"] == "вмерзла":
            continue                    # план пересобран: идём дальше
        time.sleep(пауза_с)
    итог = заход_итог(дом)
    _журнал_строка(дом, f"цикл закончен: шагов {шагов}, частей "
                        f"{итог['ок']}/{итог['частей']}")
    return {"шагов": шагов, **итог}


def отвязать(дом: Path | None = None, минут: float = 30.0) -> dict:
    """Отвязанный фон: наш собственный процесс (своя сессия), pid в файле,
    лог в файле; стоп — файлом. Платформа тут ни при чём."""
    дом = Path(дом) if дом else КОРЕНЬ
    жив = _фон_активен(дом)
    if жив:
        return {"фон": "уже идёт", "пид": жив}
    снять_стоп(дом)
    лог = (дом / ЛОГ).open("a", encoding="utf-8")
    проц = subprocess.Popen(
        [sys.executable, str(Path(__file__).resolve()), str(дом),
         "--цикл", str(минут)],
        cwd=дом, stdout=лог, stderr=subprocess.STDOUT, start_new_session=True)
    (дом / ПИД).write_text(f"{проц.pid} {datetime.now().isoformat(timespec='seconds')}",
                           encoding="utf-8")
    return {"фон": "запущен", "пид": проц.pid, "минут": минут}


def _журнал_строка(дом: Path, текст: str) -> None:
    строка = f"- {datetime.now():%d.%m.%Y %H:%M:%S} · {текст}"
    with (дом / ЛОГ).open("a", encoding="utf-8") as ф:
        ф.write(строка + "\n")
    # Контракт CI: stdout принадлежит ДАННЫМ (--plan-json читают парсером),
    # поэтому человеческий лог идёт в stderr.
    print(строка, file=sys.stderr)


def заход_итог(дом: Path | None = None) -> dict:
    ж = загрузить(дом)
    ок = sum(1 for ч in ж["части"] if ч.get("статус") == "ок")
    провалы = [ч["имя"] for ч in ж["части"] if ч.get("статус") == "провал"]
    вмерзли = [ч["имя"] for ч in ж["части"] if ч.get("статус") == "вмерзла"]
    время = round(sum(ч.get("время_с", 0.0) for ч in ж["части"]), 1)
    return {"состояние": ж.get("состояние", "нет"), "частей": len(ж["части"]),
            "ок": ок, "провалы": провалы, "вмерзли": вмерзли, "секунд": время,
            "бюджет_с": ж.get("бюджет_с", 0)}


def вскрытие(дом: Path | None = None) -> dict:
    """Автопсия красных частей: кто упал, на чём, что делать (школа разбора
    «сократить → локализовать → починить → красный тест»)."""
    дом = Path(дом) if дом else КОРЕНЬ
    ж = загрузить(дом)
    красные = [ч for ч in ж["части"] if ч.get("статус") in ("провал", "вмерзла")]
    строки = ["# Вскрытие полигона", ""]
    if not красные:
        строки.append("Красных частей нет — вскрывать нечего.")
    for ч in красные:
        строки.append(f"## {ч['имя']} — {ч.get('статус')} "
                      f"({ч.get('время_с')}с)")
        строки.append(f"- хвост: {ч.get('хвост') or '—'}")
        for п in (ч.get("падений") or [])[:12]:
            строки.append(f"- упал: `{п}`")
        if not ч.get("падений"):
            строки.append("- падений поимённо нет (или часть вмерзла)")
        строки.append("- путь разбора: сократить вход → локализовать → "
                      "починить → красный тест")
        строки.append("")
    (дом / ВСКРЫТИЕ).write_text("\n".join(строки) + "\n", encoding="utf-8")
    return {"красных": len(красные)}


def статус(дом: Path | None = None) -> dict:
    дом = Path(дом) if дом else КОРЕНЬ
    ж = загрузить(дом)
    и = заход_итог(дом)
