def _заход_свеж(журнал: dict, свежесть_ч: float = 6.0) -> bool:
    """Зелёный заход — улика, пока свеж: метка «закрыт» (или «пересобран»/
    «начат») не старше свежести. Свежесть по содержанию, не по mtime."""
    метка = (журнал.get("закрыт") or журнал.get("пересобран")
             or журнал.get("начат") or "")
    try:
        когда = datetime.fromisoformat(метка)
    except ValueError:
        return False
    return (datetime.now() - когда).total_seconds() <= свежесть_ч * 3600


