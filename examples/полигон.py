def _вес_узла(дом: Path, узел: str) -> float:
    """Измеренный вес узла (`файл::тест`): тяжёлый узел — в свою часть.

    Иначе `test_ритм_арсенала` (42 с) попадает в общую группу и вмерзает:
    часть краснеет средой, а не поведением (долг 30.09, тот же урок)."""
    файл = дом / УЗЛЫ_ВЕС_JSON
    if not файл.exists():
        return 0.0
    try:
        д = json.loads(файл.read_text(encoding="utf-8")).get("узлы", {})
    except Exception:
        return 0.0
    имя = узел.split("::")[-1]
    return float(д.get(имя, 0.0))


def _отпечаток_тестов(дом: Path) -> str:
    """Ключ кэша плана: имена, размеры и время тест-файлов + время замеров."""
    import hashlib
    куски = []
    for ф in sorted((дом / "examples").glob("тесты_*.py")):
        с = ф.stat()
        куски.append(f"{ф.name}:{с.st_size}:{int(с.st_mtime)}")
    фв = дом / "00_START" / "время_тестов.json"
    if фв.exists():
        куски.append("время:" + str(int(фв.stat().st_mtime)))
    return hashlib.sha1("|".join(куски).encode("utf-8")).hexdigest()[:12]


def части_по_весу(дом: Path | None = None,
                  бюджет_с: float = 36.0,
                  кэш: bool = True) -> list[dict]:
    """Нарезка боя по ИЗМЕРЕННОМУ весу (долг 30.09, v166): файл тяжелее бюджета
    делится по своим тестам — иначе толстая часть (94,7 с) вмерзает в предел
    вызова, и бой краснеет средой, а не поведением. Тяжёлые части — первыми.
    """
    дом = Path(дом) if дом else Path(__file__).resolve().parent.parent
    ключ = _отпечаток_тестов(дом)
    файл_кэша = дом / ФОТОНЫ_ВЕС_JSON
    if кэш and файл_кэша.exists():
        try:
            д = json.loads(файл_кэша.read_text(encoding="utf-8"))
            if д.get("отпечаток") == ключ and float(д.get("бюджет_с", 0)) == бюджет_с:
                return д["части"]
        except Exception:
            pass
    папка = дом / "examples"
    времена: dict = {}
    файл_времени = дом / "00_START" / "время_тестов.json"
    if файл_времени.exists():
        try:
            времена = json.loads(файл_времени.read_text(encoding="utf-8")).get("файлы", {})
        except Exception:
            времена = {}
    вес = lambda имя: float(времена.get(имя, 0.0)) or НЕИЗМЕРЕННЫЙ_ЗАПАС_С
    части: list[dict] = []
    мелкие: list[tuple[str, float]] = []
    for ф in sorted(папка.glob("тесты_*.py")):
        в = вес(ф.name)
        if в <= бюджет_с:
            мелкие.append((ф.name, в))
            continue
        узлы = _узлы_файла(ф)
        if not узлы:
            мелкие.append((ф.name, в))          # не собрался список — кладём как есть
            continue
        # 1) измеренно тяжёлые узлы — каждый своей частью (иначе группа вмерзает)
        тяжёлые = [у for у in узлы if _вес_узла(дом, у) >= бюджет_с / 2]
        обычные = [у for у in узлы if у not in set(тяжёлые)]
        for у in тяжёлые:
            # «глыба» — НАЗВАНА: узел неделим и тяжелее бюджета; судят её по
            # пределу дома (45 с), а не по бюджету части (грабли 01.10)
            части.append({"цели": [у], "тяжёлый": ф.name, "глыба": True,
                          "секунд": round(_вес_узла(дом, у), 1)})
        # 2) остальные — равными долями по оценке
        доля = max(1, int(len(обычные) * бюджет_с / в)) if обычные else 1
        for а in range(0, len(обычные), доля):
            группа = обычные[а:а + доля]
            части.append({"цели": группа, "тяжёлый": ф.name,
                          "секунд": round(в * len(группа) / len(узлы), 1)})
    тек: list[str] = []
    сумма = 0.0
    for имя, в in sorted(мелкие, key=lambda п: (-п[1], п[0])):
        if тек and сумма + в > бюджет_с:
            части.append({"цели": list(тек), "секунд": round(сумма, 1)})
            тек, сумма = [], 0.0
        тек.append(имя)
        сумма += в
    if тек:
        части.append({"цели": list(тек), "секунд": round(сумма, 1)})
    части.sort(key=lambda ч: (-ч["секунд"], ч["цели"][0]))
    for ч in части:
        ч["файлы"] = sorted({ц.split("::")[0] for ц in ч["цели"]})
    if кэш:
        try:
            файл_кэша.write_text(json.dumps(
                {"отпечаток": ключ, "бюджет_с": бюджет_с, "части": части},
                ensure_ascii=False, indent=1), encoding="utf-8")
        except OSError:
            pass
    return части


