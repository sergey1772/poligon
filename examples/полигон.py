ПОРОГ_МЕСТ_С = 1200.0    # П-6: полный прогон дольше 20 мин — части становятся


def раскладка(ж: dict) -> dict:
    """П-6: когда полный прогон дольше 20 мин, части становятся МЕСТАМИ.

    Время — не единственная ось дробления: если работы больше, чем один
    контур успевает за цикл, каждая часть обязана получить своё место
    (раннер/узел) — дом не ждёт очереди, дом раскладывает. Мера — сумма
    измеренных секунд плана, а не желание.
    """
    сумма = round(sum(float(ч.get("секунд") or 0.0) for ч in ж.get("части", [])), 1)
    if сумма > ПОРОГ_МЕСТ_С:
        return {"способ": "по местам", "мест": len(ж.get("части", [])),
                "измерено_с": сумма, "порог_с": ПОРОГ_МЕСТ_С,
                "почему": f"полный прогон {сумма}с > {int(ПОРОГ_МЕСТ_С)}с — каждой части своё место"}
    return {"способ": "по времени", "мест": 0, "измерено_с": сумма,
            "порог_с": ПОРОГ_МЕСТ_С,
            "почему": f"полный прогон {сумма}с укладывается в один контур"}


