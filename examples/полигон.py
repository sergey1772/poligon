def сводка_ci(куда: Path | str) -> dict:
    """Сводка по артефактам (латиница): вердикт ПРОД-ГОТОВ/КРАСНЫЙ и главная
    проверка — не вышел ли хоть один вызов за 50 с (Статья 56 действует и на
    серверах GitHub, не только дома)."""
    к = Path(куда)
    части: list[dict] = []
    for ф in sorted(к.glob("часть*.json")):
        try:
            д = json.loads(ф.read_text(encoding="utf-8"))
        except Exception:
            continue
        части.append({"номер": int(д.get("part", д.get("номер", 0))),
                      "статус": д.get("status") or _статус_ci(
                          str(д.get("статус", ""))),
                      "секунд": float(д.get("sec", д.get("секунд", 0)) or 0),
                      "хвост": д.get("tail") or д.get("хвост") or "",
                      "падений": д.get("failed") or д.get("падений") or []})
    части.sort(key=lambda ч: ч["номер"])
    ок = [ч for ч in части if ч["статус"] == "ok"]
    провалы = [ч for ч in части if ч["статус"] in ("fail", "провал")]
    вмерзли = [ч for ч in части if ч["статус"] in ("frozen", "вмерзла")]
    долгие = [ч for ч in части if ч["секунд"] > 50.0]
    проблемы = ([f"article 56: part {ч['номер']} ran {ч['секунд']}s > 50s — split"
                 for ч in долгие]
                + [f"part {ч['номер']} ({ч['статус']}): {ч['хвост'][:70]}"
                   for ч in провалы + вмерзли])
    if not части:
        проблемы.append("артефактов частей нет — судить нечего (ноль данных "
                        "не есть зелёное)")
    # Сверка с планом: неполный набор частей — не зелёное (иначе «3 из 6»
    # выглядит как PROD-READY — так и было в прогоне 36739489358).
    план_ф = к / "plan.json"
    if план_ф.exists():
        try:
            план_д = json.loads(план_ф.read_text(encoding="utf-8"))
            всего_п = int(план_д.get("total") or 0)
            есть = {ч["номер"] for ч in части}
            нет = [н for н in range(1, всего_п + 1) if н not in есть]
            if нет:
                проблемы.append(
                    f"неполный прогон: частей {len(части)} из {всего_п}, "
                    f"нет {нет} — зелёное только по полному набору")
        except Exception as е:
            проблемы.append(f"план не прочитан: {е}")
    return {"verdict": "PROD-READY" if not проблемы else "RED",
            "parts": len(части), "ok": len(ок),
            "failed_parts": [ч["номер"] for ч in провалы],
            "frozen_parts": [ч["номер"] for ч in вмерзли],
            "long_parts": [ч["номер"] for ч in долгие],
            "failures": sum(len(ч["падений"]) for ч in части),
            "seconds": round(sum(ч["секунд"] for ч in части), 1),
            "problems": проблемы,
            "failed_tests": [п for ч in части for п in ч["падений"]]}


def подготовить_клетку(дом: Path | None = None) -> dict:
    """Клетка для чужого раннера (GitHub Actions и любой другой CI).

    Дом и клетка — разные вещи: у клетки нет паузы Суверена, нет живого
    производного и нет прав ограждения. Полигон обязан сам довести клетку до
    состояния «можно мерить», иначе красное в CI — не про код, а про среду
    (Статья 34.2: отказ типа Б лечится средой, а не моделью и не уговором).

    Что делает (только в CI-клетке, GITHUB_ACTIONS=true):
      1. не наследует паузу живого дома — записывает СВОЮ паузу в клетке;
      2. регенерирует производное (свежий стандарт уроков), если его нет;
      3. докладывает, что сделано (журнал + печать).
    """
    дом = Path(дом) if дом else КОРЕНЬ
    отчёт = {"клетка": False, "пауза_снята": False, "стандарт": "есть",
             "журнал_чист": False}
    if os.environ.get("GITHUB_ACTIONS") != "true":
        return отчёт
    отчёт["клетка"] = True
    # 1) пауза живого дома не наследуется клеткой
    стоп = дом / "41_MECHANISMS" / "стоп_контур.json"
    if стоп.exists():
        try:
            import sys as _с
            _с.path.insert(0, str(дом / "examples"))
            from стоп import СтопКонтур
            к = СтопКонтур.загрузить_состояние(стоп)
            if к.пауза:
                к.пауза.clear()
                к.сохранить_состояние(стоп)
                отчёт["пауза_снята"] = True
        except Exception:
            pass
    # 2) производное в клетке: свежий стандарт (пакеты в git не хранятся)
    папка = дом / "42_УРОКИ" / "пакеты"
    нет_стандарта = not list(папка.glob("стандарт_*.json")) if папка.exists() else True
    if нет_стандарта:
        try:
            import subprocess as _п
            _п.run([sys.executable, str(дом / "examples" / "уроки.py"), "--стандарт"],
                   cwd=дом, capture_output=True, text=True, timeout=45)
            отчёт["стандарт"] = "собран"
        except Exception:
            отчёт["стандарт"] = "не собран"
    # 3) журнал прогонов в клетке — свой: история мер дома не есть мера клетки
    #    (иначе CI берёт части «из журнала», не меряя ничего вовсе). План
    #    остаётся (без него «части нет в плане»), а статусы обнуляются.
    try:
        было = bool(загрузить(дом).get("части"))
        # бюджет ТОТ ЖЕ, что у матрицы: иначе хвост частей «нет в плане»
        # (улика 01.10: 7 зелёных, 4 красных, «части 8 нет в плане»)
        ж = начать(дом, бюджет_с=БЮДЖЕТ_ЧАСТИ_С_CI)   # свежий план по мераследуются
        _сохранить(дом, ж)
        отчёт["журнал_чист"] = было
    except Exception:
        отчёт["журнал_чист"] = False
    _журнал_строка(дом, f"клетка CI: пауза снята {отчёт['пауза_снята']}, "
                        f"стандарт {отчёт['стандарт']}, "
                        f"журнал {'чист' if отчёт.get('журнал_чист') else 'свой'}")
    return отчёт


