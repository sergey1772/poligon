"""Полигон (Х-21 · О-17; слово Суверена 30.09: «Система „Полигон“, особенно её
фоновый режим, мне очень понравилась… сделать полностью системой „Спрута“.
Фотонность внутри полигона обязательна»).

Что это. Полигон — наш собственный ранер полного прогона тестов: он дробит
работу по ИЗМЕРЕННОЙ мере, гоняет по одной части за вызов (Статья 56: ≤45 с),
пишет журнал на диск (обрыв процесса не теряет сделанного), умеет:

  * `--начать`   — замёрзший план частей (имена стабильны между вызовами);
  * `--часть N`  — одна часть за один вызов (Фотонность: вызов ≤45 с);
  * `--цикл`     — фоновый цикл частей в текущем процессе (для рога платформы);
  * `--фон`      — отвязанный фоновый цикл (pid · лог · стоп-файл) — наш
                   собственный, не платформенный;
  * `--статус`   — где мы и что дальше;
  * `--стоп`     — мягкая остановка фона (стоп-файл, не убийство);
  * `--вскрытие` — разбор падений: улики по каждой красной части;
  * `--итог`     — вердикт полигона.

Почему так. Песочница — сосед: длинный вызов её убивает. Поэтому у полигона
нет ни одного вызова дольше предела (45 с), а вся память о ходе лежит в
журнале, а не в процессе. Фон — это не «повесить песочницу», а «идти
маленькими шагами, пока не закончится план или пока Суверен не скажет стоп».
"""

