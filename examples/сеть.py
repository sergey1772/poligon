def _узлы_кода(дом: Path, узлы: dict, рёбра: list) -> dict:
    """Механизмы и тесты: каждый `examples/*.py` — узел со своим отпечатком."""
    примеры = Path(дом) / "examples"
    статистика = {"файлов": 0, "импортов": 0, "пропущено": 0}
    исходники: dict[str, str] = {}
    for ф in sorted(примеры.glob("*.py")):
        род = "тест" if ф.name.startswith("тесты_") else "механизм"
        байт = ф.read_bytes()
        док = _докстринг(байт.decode("utf-8", "replace"))
        узлы[f"{род}:{ф.name}"] = {
            "род": род, "имя": ф.name, "путь": f"examples/{ф.name}",
            "о": док.split(".")[0][:90], "о_полн": док[:400],
            "отпечаток": _отпечаток(байт), "байт": len(байт)}
        исходники[ф.stem] = байт.decode("utf-8", "replace")
        статистика["файлов"] += 1
    for имя, текст in исходники.items():
        for цель in _модули_из_источника(текст):
            ссылка = f"механизм:{цель}.py"
            ссылка_тест = f"тест:{цель}.py"
            к = ссылка if ссылка in узлы else (ссылка_тест if ссылка_тест in узлы else None)
            if к is None:
                статистика["пропущено"] += 1     # импорт в пустоту — не ребро
                continue
            от = (f"тест:{имя}.py" if f"тест:{имя}.py" in узлы
                  else f"механизм:{имя}.py")
            рёбра.append({"от": от, "к": к, "род": "зовёт", "вес": 1.0,
                          "улика": f"import {цель}"})
            статистика["импортов"] += 1
    return статистика


def _докстринг(текст: str) -> str:
    """Первая строка-описание файла: сеть ищет по ней, как по имени."""
    м = re.search(r'"""(.*?)"""', текст[:6000], flags=re.S)   # шапки бывают длинными
    return " ".join(м.group(1).split()) if м else ""


def _модули_из_источника(текст: str) -> list[str]:
    """Имена внутренних модулей из import-строк (без исполнения кода)."""
    имена: list[str] = []
    for строка in текст.splitlines():
        с = строка.strip()
        м = re.match(r"^import\s+([\w\u0400-\u04FF]+)", с)
        if м:
            имена.append(м.group(1))
            continue
        м = re.match(r"^from\s+([\w\u0400-\u04FF]+)\s+import\s+", с)
        if м:
            имена.append(м.group(1))
    return sorted(set(имена))


def _узлы_органов(дом: Path, узлы: dict, рёбра: list) -> dict:
    """Органы — из таблицы дома (`42_УРОКИ/таблицы/органы.json`), не из кода."""
    файл = Path(дом) / "42_УРОКИ" / "таблицы" / "органы.json"
    статистика = {"клеток": 0, "где_связано": 0}
    if not файл.exists():
        return статистика
    try:
        д = json.loads(файл.read_text(encoding="utf-8"))
    except Exception:
        return статистика
    for к in д.get("клетки", []):
        ид = str(к.get("ид", "")).strip()
        if not ид:
            continue
        узлы[f"орган:{ид}"] = {"род": "орган", "имя": к.get("имя", ид),
                               "состояние": к.get("состояние", ""),
                               "слой": к.get("слой"),
                               "что": str(к.get("что", ""))[:240]}
        статистика["клеток"] += 1
        где = str(к.get("где", "") or "")
        имя = где.split("/")[-1].strip()
        if имя and f"механизм:{имя}" in узлы:
            рёбра.append({"от": f"орган:{ид}", "к": f"механизм:{имя}",
                          "род": "где", "вес": 1.0, "улика": f"где={где}"})
            статистика["где_связано"] += 1
    return статистика


def _узлы_уроков(дом: Path, узлы: dict, рёбра: list) -> dict:
    """Уроки — из базы дома: узел урока и ребро «знает» к области."""
    файл = Path(дом) / "42_УРОКИ" / "база_уроков.md"
    статистика = {"уроков": 0, "областей": 0}
    if not файл.exists():
        return статистика
    текст = файл.read_text(encoding="utf-8")
    области: set[str] = set()
    for блок in re.findall(r"```json\s*\n(.*?)\n```", текст, flags=re.S):
        try:
            д = json.loads(блок)
        except Exception:
            continue
        ид = str(д.get("ид", "")).strip()
        область = str(д.get("область", "")).strip()
        if not ид:
            continue
        узлы[f"урок:{ид}"] = {"род": "урок", "имя": ид,
                              "класс": д.get("класс", ""),
                              "петля": д.get("петля", ""),
                              "область": область,
                              "триггер": str(д.get("триггер", ""))[:240],
                              "отпечаток": _отпечаток(блок.encode("utf-8"))}
        статистика["уроков"] += 1
        if область:
            области.add(область)
            рёбра.append({"от": f"урок:{ид}", "к": f"область:{область}",
                          "род": "знает", "вес": 1.0, "улика": ид})
    for область in sorted(области):
        узлы[f"область:{область}"] = {"род": "область", "имя": область}
        статистика["областей"] += 1
    return статистика


# ── проверки сети ────────────────────────────────────────────────────────────

def _циклы(узлы: dict, рёбра: list) -> list[list[str]]:
    """Циклы в «зовёт»: сеть без предохранителя обязана их хотя бы видеть."""
    смежные: dict[str, list[str]] = {}
    for р in рёбра:
        if р["род"] == "зовёт":
            смежные.setdefault(р["от"], []).append(р["к"])
    найдено: list[list[str]] = []
    цвет: dict[str, int] = {}

    def обход(у: str, путь: list[str]) -> None:
        if len(найдено) >= 5:
            return
        цвет[у] = 1
        for с in смежные.get(у, []):
            if цвет.get(с) == 1:
                найдено.append(путь[путь.index(с):] + [с])
            elif цвет.get(с, 0) == 0:
                обход(с, путь + [с])
        цвет[у] = 2

    for у in sorted(узлы):
        if цвет.get(у, 0) == 0:
            обход(у, [у])
    return найдено


def _висячие(узлы: dict, рёбра: list) -> list[dict]:
    return [р for р in рёбра if р["от"] not in узлы or р["к"] not in узлы]


# ── сборка и сводка ─────────────────────────────────────────────────────────

def собрать(дом: Path | str | None = None, куда: Path | str | None = None) -> dict:
    """Собрать сеть дома: узлы и нити из адаптеров, производное — в `41_MECHANISMS/сеть/`.

    Один вызов — весь дом (≤45 с). Возвращает сводку; на диск кладёт узлы.jsonl,
    рёбра.jsonl и сводка.json (атомарно: сборка не оставляет половины).
    """
    дом = Path(дом) if дом else КОРЕНЬ
    тик = time.perf_counter()
    узлы: dict[str, dict] = {}
    рёбра: list[dict] = []
    адаптеры = {
        "код": _узлы_кода(дом, узлы, рёбра),
        "органы": _узлы_органов(дом, узлы, рёбра),
        "уроки": _узлы_уроков(дом, узлы, рёбра),
    }
    # дедуп рёбер (одна связь — одна нить)
    ключи: set[tuple] = set()
    чисто: list[dict] = []
    for р in рёбра:
        кл = (р["от"], р["к"], р["род"])
        if кл in ключи:
            continue
        ключи.add(кл)
        чисто.append(р)
    рёбра = чисто
    циклы = _циклы(узлы, рёбра)
    висячие = _висячие(узлы, рёбра)
    секунд = round(time.perf_counter() - тик, 2)
    по_родам = {р: sum(1 for у in узлы.values() if у["род"] == р) for р in РОДА_УЗЛОВ}
    по_нити = {р: sum(1 for х in рёбра if х["род"] == р) for р in РОДА_РЁБЕР}
    сводка = {"когда": datetime.now().isoformat(timespec="seconds"),
              "узлов": len(узлы), "рёбер": len(рёбра), "секунд": секунд,
              "по_родам_узлов": по_родам, "по_родам_рёбер": по_нити,
              "циклов": len(циклы), "циклы": [ц[:6] for ц in циклы],
              "висячих": len(висячие), "адаптеры": адаптеры,
              "здоровье": "чисто" if not висячие and not циклы else "смотри циклы"}
    п = Path(куда) if куда else _папка(дом)
    _атомарно(п / "узлы.jsonl", "".join(
        json.dumps({"ид": и, **у}, ensure_ascii=False) + "\n"
        for и, у in sorted(узлы.items())))
    _атомарно(п / "рёбра.jsonl", "".join(
        json.dumps(р, ensure_ascii=False) + "\n" for р in рёбра))
    _атомарно(п / "сводка.json", json.dumps(сводка, ensure_ascii=False, indent=1))
    return сводка


def _атомарно(путь: Path, текст: str) -> None:
    вр = путь.with_suffix(путь.suffix + ".tmp")
    вр.write_text(текст, encoding="utf-8")
    вр.replace(путь)


def сводка(дом: Path | str | None = None) -> dict:
    """Сводка сети: из диска, если собрана; иначе — свежая сборка (одним вызовом)."""
    п = _папка(Path(дом) if дом else КОРЕНЬ) / "сводка.json"
    if п.exists():
        try:
            return json.loads(п.read_text(encoding="utf-8"))
        except Exception:
            pass
    return собрать(дом)



