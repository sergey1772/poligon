БАЗА_УРОКОВ = "42_УРОКИ/база_уроков.md"


def _журнал_маршрутов(дом: Path) -> Path:
    return _папка(дом) / "маршруты.jsonl"


def _ключ_задачи(задача: str) -> str:
    """Ключ повтора: слова без порядка — «собрать сеть дома» = «сеть дома собрать»."""
    return " ".join(sorted(set(_токены(задача))))


def _свидетели_пути(дом: Path, узлы: dict, рёбра: list, путь: list[str]) -> dict:
    """Свидетели маршрута: файлы, чья правка обязана снять миелин (мозоль сходит).

    Механизм и тест — свой файл; орган — файл из нити «где»; урок и область —
    база уроков. Свидетель без отпечатка не бывает: иначе кеш живёт ложью.
    """
    файлы: set[str] = set()
    for ид in путь:
        у = узлы.get(ид, {})
        род = у.get("род")
        if род in ("механизм", "тест") and у.get("путь"):
            файлы.add(у["путь"])
        elif род == "орган":
            for р in рёбра:
                if р["от"] == ид and р["род"] == "где":
                    файлы.add("examples/" + р["к"].split(":", 1)[1])
        elif род in ("урок", "область"):
            файлы.add(БАЗА_УРОКОВ)
    свид: dict[str, str] = {}
    for ф in sorted(файлы):
        п = дом / ф
        if п.exists():
            свид[ф] = _отпечаток(п.read_bytes())
    return свид


def зацементировать(задача: str, дом: Path | str | None = None,
                    улика: str = "") -> dict:
    """Полный маршрут → запись в маршруты.jsonl: путь и отпечатки свидетелей."""
    дом = Path(дом) if дом else КОРЕНЬ
    узлы, рёбра = _загрузить_сеть(дом)
    и = маршрут(задача, дом, писать_журнал=False)
    if not и["выбран"]:
        return {"цемент": False, "почему": "маршрут пуст: цементировать нечего"}
    путь = [ш["узел"] for ш in и["шаги"]]
    свид = _свидетели_пути(дом, узлы, рёбра, путь)
    if not свид:
        return {"цемент": False, "почему": "нет свидетелей: кеш был бы ложью"}
    запись = {"когда": datetime.now().isoformat(timespec="seconds"),
              "ключ": _ключ_задачи(задача), "задача": задача,
              "улика": улика or "полный маршрут пройден",
              "путь": путь, "шаги": и["шаги"], "свидетели": свид}
    with _журнал_маршрутов(дом).open("a", encoding="utf-8") as ф:
        ф.write(json.dumps(запись, ensure_ascii=False) + "\n")
    return {"цемент": True, "ключ": запись["ключ"], "путь": путь,
            "свидетелей": len(свид), "улика": запись["улика"]}


def _последняя_запись(дом: Path, ключ: str) -> dict | None:
    жф = _журнал_маршрутов(дом)
    if not жф.exists():
        return None
    найдено = None
    for строка in жф.read_text(encoding="utf-8").splitlines():
        if not строка.strip():
            continue
        try:
            д = json.loads(строка)
        except Exception:
            continue
        if д.get("ключ") == ключ:
            найдено = д
    return найдено


def _живость(дом: Path, запись: dict) -> tuple[bool, str]:
    """Свидетели сверяются с ДИСКОМ: подмена кеша не спасает — ложь не пройдёт."""
    for файл, отп in (запись.get("свидетели") or {}).items():
        п = дом / файл
        if not п.exists():
            return False, f"пропал свидетель {файл}"
        if _отпечаток(п.read_bytes()) != отп:
            return False, f"правился свидетель {файл}"
    return True, "свидетели живы"


def миелин(задача: str, дом: Path | str | None = None,
           писать_журнал: bool = False) -> dict:
    """Быстрый путь: повтор цементированного маршрута, если свидетели живы.

    Промах или порча свидетеля — честный полный маршрут; старый путь никогда
    не отдаётся поверх правки (иначе кеш жил бы ложью).
    """
    дом = Path(дом) if дом else КОРЕНЬ
    тик = time.perf_counter()
    ключ = _ключ_задачи(задача)
    запись = _последняя_запись(дом, ключ)
    if запись is None:
        и = маршрут(задача, дом, писать_журнал=писать_журнал)
        return {**и, "источник": "полный", "улика": "не цементировано: полный маршрут"}
    живо, почему = _живость(дом, запись)
    if not живо:
        и = маршрут(задача, дом, писать_журнал=писать_журнал)
        return {**и, "источник": "инвалидация",
                "улика": f"мозоль сходит ({почему}) — полный маршрут"}
    секунд = round(time.perf_counter() - тик, 4)
    путь = запись.get("путь") or []
    return {"задача": задача, "выбран": путь[0] if путь else "",
            "шаги": запись.get("шаги", []),
            "источник": "миелин", "секунд": секунд,
            "улика": (f"миелин от {запись['когда']}: {запись['улика']}; "
                      f"свидетелей {len(запись.get('свидетели') or {})} — живы")}


def маршруты(дом: Path | str | None = None) -> dict:
    """Сводка журнала цементов: сколько путей, свежих и сошедших мозолей."""
    дом = Path(дом) if дом else КОРЕНЬ
    жф = _журнал_маршрутов(дом)
    последние: dict[str, dict] = {}
    if жф.exists():
        for строка in жф.read_text(encoding="utf-8").splitlines():
            if строка.strip():
                try:
                    д = json.loads(строка)
                except Exception:
                    continue
                последние[д.get("ключ", "")] = д
    свежих, сошли = 0, []
    for ключ, д in последние.items():
        живо, почему = _живость(дом, д)
        if живо:
            свежих += 1
        else:
            сошли.append({"ключ": ключ, "задача": д.get("задача", ""),
                          "почему": почему})
    return {"путей": len(последние), "свежих": свежих, "сошли": сошли}


