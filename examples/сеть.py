def _токены(задача: str) -> list[str]:
    слова = re.findall(r"[а-яёa-z0-9]{3,}", задача.lower())
    годные = {т for т in слова
              if (len(т) >= 4 or т in КОРОТКИЕ_СЛОВА)
              and т not in СТОП_СЛОВА}
    return sorted({СИНОНИМЫ.get(т, т) for т in годные})


def _норм(текст: str) -> str:
    """Сравнимое имя: «органы_кэш.py» → «органы кэш»."""
    т = текст.lower().strip()
    if т.endswith(".py"):
        т = т[:-3]
    return т.replace("_", " ").replace("-", " ").strip()


def _имя_узла(узел: dict) -> str:
    return _норм(str(узел.get("имя", "")))


def _варианты(токен: str) -> list[str]:
    в = [токен]
    if len(токен) > 5:
        в.append(токен[:-1])
        в.append(токен[:-2])
    return в


def _оценка(узел: dict, токены: list[str], заявка: str = "",
            род_запроса: str = "", ид_узла: str = "") -> tuple[float, list[dict]]:
    """Оценка узла словами задачи; каждая улика называет слово и место."""
    поля = {"имя": узел.get("имя", "").lower(),
            "о": (узел.get("о_полн") or узел.get("о", "")).lower(),
            "что": str(узел.get("что", "")).lower(),
            "триггер": str(узел.get("триггер", "")).lower(),
            "область": str(узел.get("область", "")).lower()}
    счёт, улики = 0.0, []
    учтённые_поля: set[str] = set()
    род = узел.get("род", "")
    вес_имени = ВЕС_ИМЕНИ.get(род, 3.0)
    for токен in токены:
        варианты = _варианты(токен)
        if поля["имя"] and any(в in поля["имя"] for в in варианты):
            счёт += вес_имени
            улики.append({"токен": токен, "где": "имя"})
        for имя_поля, вес in ПОЛЯ_ПОИСКА:
            if имя_поля in учтённые_поля:
                continue                      # описание — слабая улика: раз на узел
            текст = поля.get(имя_поля, "")
            if текст and any(в in текст for в in варианты):
                счёт += вес
                улики.append({"токен": токен, "где": имя_поля})
                учтённые_поля.add(имя_поля)
    счёт += ПРИОРИТЕТ_РОДА.get(род, 0.0)
    # точное имя: имя узла названо целиком (спасает короткие и составные имена)
    имя_узла = _имя_узла(узел)
    заявка_н = _норм(заявка)
    if имя_узла and заявка_н:
        if имя_узла == заявка_н or имя_узла.replace(" ", "") == заявка_н.replace(" ", ""):
            счёт += БОНУС_ТОЧНОГО_ИМЕНИ
            улики.append({"токен": имя_узла, "где": "имя узла точно"})
        elif len(имя_узла) >= 4 and (имя_узла in заявка_н or заявка_н in имя_узла):
            счёт += БОНУС_ТОЧНОГО_ИМЕНИ / 3
            улики.append({"токен": имя_узла, "где": "имя узла в заявке"})
    # ид узла — тоже имя: органы зовутся «О-13», а «имя» у них поэтическое
    ид_хвост = _норм(ид_узла.split(":")[-1]) if ид_узла else ""
    if ид_хвост and заявка_н and ид_хвост == заявка_н:
        счёт += БОНУС_ТОЧНОГО_ИМЕНИ * 0.8
        улики.append({"токен": ид_хвост, "где": "ид узла точно"})
    if род_запроса and род and род == род_запроса:
        счёт += БОНУС_РОДА_ЗАПРОСА
        улики.append({"токен": род, "где": "тот же род, что у заявки"})
    имя = узел.get("имя", "").lower()
    if имя.endswith(".py"):
        база = имя[:-3]
        if база and any(база in _варианты(т) for т in токены):
            счёт += БОНУС_ИМЕНИ_ФАЙЛА     # файл назван ровно этим словом
            улики.append({"токен": база, "где": "имя файла"})
        счёт -= ШТРАФ_ЗА_СОСТАВ * база.count("_")
    return счёт, улики


def _загрузить_сеть(дом: Path) -> tuple[dict, list]:
    п = _папка(дом)
    узел_ф, реб_ф = п / "узлы.jsonl", п / "рёбра.jsonl"
    if not (узел_ф.exists() and реб_ф.exists()):
        собрать(дом)
    узлы = {}
    for строка in узел_ф.read_text(encoding="utf-8").splitlines():
        if строка.strip():
            д = json.loads(строка)
            узлы[д.pop("ид")] = д
    рёбра = [json.loads(с) for с in реб_ф.read_text(encoding="utf-8").splitlines()
             if с.strip()]
    return узлы, рёбра


def _лучший_узел(узлы: dict, токены: list[str], заявка: str = "",
                род_запроса: str = "") -> tuple[str, float, list[dict]]:
    """Лучший узел для слов задачи: ничья — первый по порядку сети (как в развилке).

    Заявка и род — необязательная подсказка: обход знает, КОГО предъявляет
    (имя целиком и род), развилка не знает — она по-прежнему судит по словам."""
    лучший, счёт_лучшего, улики_лучшего = "", -1.0, []
    for ид, узел in узлы.items():
        счёт, улики = _оценка(узел, токены, заявка=заявка,
                              род_запроса=род_запроса, ид_узла=ид)
        if счёт > счёт_лучшего:
            лучший, счёт_лучшего, улики_лучшего = ид, счёт, улики
    return лучший, счёт_лучшего, улики_лучшего


def маршрут(задача: str, дом: Path | str | None = None, бюджет_шагов: int = 12,
            писать_журнал: bool = True) -> dict:
    """Развилка: задача → маршрут по узлам, КАЖДЫЙ шаг называет причину.

    Без модели: слова задачи ищутся в имени узла и его описании, затем маршрут
    идёт по нитям (зовёт/знает/где). Дольше 2 с не бывает: это поиск, не думание.
    """
    дом = Path(дом) if дом else КОРЕНЬ
    тик = time.perf_counter()
    узлы, рёбра = _загрузить_сеть(дом)
    токены = _токены(задача)
    лучший, лучший_счёт, лучшие_улики = _лучший_узел(узлы, токены)
    if not лучший:
        return {"задача": задача, "выбран": "", "шаги": [], "улики": [],
                "секунд": 0.0, "причина": "пусто: слов не нашлось"}
    выбран_узел = узлы[лучший]
    слова = ", ".join(f"«{у['токен']}» в {у['где']}" for у in лучшие_улики[:3]) \
        or "прямых слов нет"
    шаги = [{"узел": лучший, "почему": f"слова задачи: {слова}"}]
    видели = {лучший}

    вход = [р for р in рёбра if р["к"] == лучший]
    исход = [р for р in рёбра if р["от"] == лучший]

    def добавить(ид: str, почему: str) -> None:
        if ид in видели or len(шаги) >= max(1, бюджет_шагов):
            return
        видели.add(ид)
        шаги.append({"узел": ид, "почему": почему})

    род = выбран_узел.get("род")
    if род == "механизм":
        for р in вход:
            if р["род"] == "зовёт" and р["от"].startswith("тест:"):
                добавить(р["от"], f"тест зовёт этот файл ({р['улика']})")
        for р in вход:
            if р["род"] == "где":
                добавить(р["от"], f"орган стоит на этом файле ({р['улика']})")
    elif род == "тест":
        for р in исход:
            if р["род"] == "зовёт":
                добавить(р["к"], f"этот тест зовёт файл ({р['улика']})")
    elif род == "орган":
        for р in исход:
            if р["род"] == "где":
                добавить(р["к"], f"орган живёт в этом файле ({р['улика']})")
    elif род == "урок":
        for р in исход:
            if р["род"] == "знает":
                добавить(р["к"], f"урок знает область ({р['улика']})")
    elif род == "область":
        свои = [р["от"] for р in вход if р["род"] == "знает"][:3]
        for ид in свои:
            добавить(ид, "урок этой области (знает)")
    секунд = round(time.perf_counter() - тик, 2)
    итог = {"задача": задача, "выбран": лучший, "о": выбран_узел.get("о", ""),
            "шаги": шаги, "улики": лучшие_улики, "секунд": секунд,
            "причина": шаги[0]["почему"]}
    if писать_журнал:
        строка = json.dumps({к: итог[к] for к in
                             ("задача", "выбран", "секунд", "причина")},
                            ensure_ascii=False)
        with (_папка(дом) / "развилки.jsonl").open("a", encoding="utf-8") as ф:
            ф.write(строка + "\n")
    return итог


def развилки(дом: Path | str | None = None) -> dict:
    """Приёмка Волны 2: 20 типовых задач дома — совпадение с ручным выбором."""
    дом = Path(дом) if дом else КОРЕНЬ
    тик = time.perf_counter()
    совпало, промахи, журнал = 0, [], []
    for задача, ждём in ТИПОВЫЕ:
        и = маршрут(задача, дом, писать_журнал=False)
        ок = и["выбран"] == ждём
        совпало += int(ок)
        if not ок:
            промахи.append({"задача": задача, "ждём": ждём,
                            "выбран": и["выбран"]})
        журнал.append({"когда": datetime.now().isoformat(timespec="seconds"),
                       "задача": задача, "выбран": и["выбран"], "ждём": ждём,
                       "совпало": ок, "секунд": и["секунд"],
                       "причина": и["причина"]})
    всего = len(ТИПОВЫЕ)
    доля = round(совпало / всего, 3) if всего else 0.0
    with (_папка(дом) / "развилки.jsonl").open("a", encoding="utf-8") as ф:
        for з in журнал:
            ф.write(json.dumps(з, ensure_ascii=False) + "\n")
    return {"всего": всего, "совпало": совпало, "доля": доля,
            "секунд": round(time.perf_counter() - тик, 2), "промахи": промахи}


# ── Гебб без backprop (Волна 3 плана): опыт усиливает связи ─────────────────

ГЕББ_ШАГ = 0.1                 # «спайк вместе — нить вместе»: один исход = шаг
ПОЛ_ВЕСА, ПОТОЛОК_ВЕСА = 0.1, 3.0
БОЕВЫЕ_ТЕСТЫ = ("тест:тесты_боя.py", "тест:тесты_полигона.py")


def _ключ_нити(р: dict) -> str:
    return f"{р['от']} → {р['к']} ({р['род']})"


def _журнал_весов(дом: Path) -> Path:
    return _папка(дом) / "веса_журнал.jsonl"


def пересчитать_веса(дом: Path | str | None = None) -> dict:
    """Веса — ПРОЕКЦИЯ журнала (append-only): журнал первичен, веса вторичны."""
    дом = Path(дом) if дом else КОРЕНЬ
    веса: dict[str, float] = {}
    for строка in (_журнал_весов(дом).exists() and
                   _журнал_весов(дом).read_text(encoding="utf-8").splitlines() or []):
        if not строка.strip():
            continue
        try:
            д = json.loads(строка)
        except Exception:
            continue
        после = д.get("вес_после", д.get("стало"))
        if после is None or "нить" not in д:
            continue
        веса[д["нить"]] = float(после)
    return {к: round(v, 4) for к, v in веса.items()}


def веса(дом: Path | str | None = None) -> dict:
    дом = Path(дом) if дом else КОРЕНЬ
    файл = _папка(дом) / "веса.json"
    if файл.exists():
        try:
            д = json.loads(файл.read_text(encoding="utf-8"))
            return {к: float(v) for к, v in д.get("нити", {}).items()}
        except Exception:
            pass
    return пересчитать_веса(дом)


def _свежие_улики(дом: Path, ключ: str) -> set[str]:
    уже: set[str] = set()
    if not _журнал_весов(дом).exists():
        return уже
    for строка in _журнал_весов(дом).read_text(encoding="utf-8").splitlines():
        if not строка.strip():
            continue
        try:
            д = json.loads(строка)
        except Exception:
            continue
        if д.get("нить") == ключ:
            уже.add(str(д.get("улика", "")))
    return уже


def усилить(дом: Path | str | None, нити: list[dict], исход: str,
            улика: str, почему: str = "") -> dict:
    """Один исход — один шаг веса. Без улики отказ: ложное самоусиление не живёт.

    Возвращает отчёт: обновлено/пропущено/отказы; журнал — append-only,
    `веса.json` пересобирается из журнала (никогда не правится руками).
    """
    дом = Path(дом) if дом else КОРЕНЬ
    if not улика.strip():
        return {"обновлено": 0, "пропущено": 0, "отказ": "нет улики — ложное самоусиление"}
    дельта = ГЕББ_ШАГ if исход == "успех" else -ГЕББ_ШАГ
    текущие = пересчитать_веса(дом)
    обновлено, пропущено = 0, 0
    строки = []
    for р in нити:
        ключ = _ключ_нити(р)
        if улика in _свежие_улики(дом, ключ):
            пропущено += 1
            continue
        было = текущие.get(ключ, 1.0)
        стало = min(ПОТОЛОК_ВЕСА, max(ПОЛ_ВЕСА, round(было + дельта, 4)))
        текущие[ключ] = стало
        обновлено += 1
        строки.append({"когда": datetime.now().isoformat(timespec="seconds"),
                       "улика": улика, "нить": ключ, "вес_было": было,
                       "вес_после": стало, "дельта": round(стало - было, 4),
                       "почему": почему or f"исход «{исход}»"})
    if строки:
        with _журнал_весов(дом).open("a", encoding="utf-8") as ф:
            for с in строки:
                ф.write(json.dumps(с, ensure_ascii=False) + "\n")
        _атомарно(_папка(дом) / "веса.json",
                  json.dumps({"когда": datetime.now().isoformat(timespec="seconds"),
                              "нити": текущие, "улик": len(строки)},
                             ensure_ascii=False, indent=1))
    return {"обновлено": обновлено, "пропущено": пропущено, "отказ": "",
            "строки": строки}


def нити_тестов(дом: Path | str, файлы: list[str]) -> list[dict]:
    """Нити прогона: «зовёт» от теста к механизму — след, которым шёл опыт."""
    дом = Path(дом) if дом else КОРЕНЬ
    _, рёбра = _загрузить_сеть(дом)
    хочу = set()
    for и in файлы:
        имя = и.split("::", 1)[0].strip()
        имя = имя.split("/")[-1]
        if имя:
            хочу.add(f"тест:{имя}" if not имя.startswith("тест:") else имя)
    return [р for р in рёбра if р["род"] == "зовёт" and р["от"] in хочу]


def нити_боевые(дом: Path | str | None = None) -> list[dict]:
    дом = Path(дом) if дом else КОРЕНЬ
    _, рёбра = _загрузить_сеть(дом)
    return [р for р in рёбра if р["род"] == "зовёт" and р["от"] in БОЕВЫЕ_ТЕСТЫ]


def сигналы_дома(дом: Path | str | None = None, боёв: int = 3) -> list[dict]:
    """Исходы, которые дом УЖЕ записал: части полигона, CI-итог, последние бои.

    Каждый сигнал несёт улику и исход — веса меняются только по свидетельствам.
    """
    дом = Path(дом) if дом else КОРЕНЬ
    сигналы: list[dict] = []
    жф = дом / "00_START" / "полигон_журнал.json"
    части = []
    if жф.exists():
        try:
            ж = json.loads(жф.read_text(encoding="utf-8"))
            части = ж.get("части", [])
            начат = ж.get("начат", "")
            for ч in части:
                статус = ч.get("статус")
                if статус not in ("ок", "провал"):
                    continue
                сигналы.append({"исход": "успех" if статус == "ок" else "провал",
                                "улика": f"полигон:{начат}:{ч.get('номер')}",
                                "файлы": [str(ф) for ф in ч.get("файлы", [])],
                                "почему": f"полигон: {ч.get('имя')} → {статус}"})
        except Exception:
            pass
    иf = дом / "00_START" / "poligon_itog.json"
    if иf.exists():
        try:
            и = json.loads(иf.read_text(encoding="utf-8"))
            ок = (и.get("verdict") == "PROD-READY" and и.get("ok") == и.get("parts"))
            файлы = [str(ф) for ч in части for ф in ч.get("файлы", [])]
            if файлы:
                сигналы.append({"исход": "успех" if ок else "провал",
                                "улика": f"ворота:CI:{и.get('run')}",
                                "файлы": файлы,
                                "почему": f"CI {и.get('run')}: {и.get('verdict')} "
                                          f"{и.get('ok')}/{и.get('parts')}"})
        except Exception:
            pass
    бф = дом / "00_START" / "журнал_боёв.md"
    if бф.exists():
        строки = [с for с in бф.read_text(encoding="utf-8").splitlines()
                  if " · хэш " in с][-max(0, боёв):]
        for с in строки:
            поля = с.split(" · ")
            дата = поля[0].lstrip("- ").strip()
            вердикт = поля[2] if len(поля) > 2 else ""
            хэш = с.rsplit(" · хэш ", 1)[-1].strip()[:12]
            сигналы.append({"исход": "успех" if вердикт.startswith("ПРОД-ГОТОВ") else "провал",
                            "улика": f"бой:{дата}:{хэш}",
                            "боевые": True,
                            "почему": f"бой {дата}: {вердикт}"})
    return сигналы


def усилить_по_дому(дом: Path | str | None = None, боёв: int = 3) -> dict:
    """Применить сигналы дома к весам нитей: успех — шаг вверх, провал — вниз."""
    дом = Path(дом) if дом else КОРЕНЬ
    тик = time.perf_counter()
    отчёт = {"сигналов": 0, "обновлено": 0, "пропущено": 0, "отказов": 0,
             "пусто": 0, "строки": []}
    for с in сигналы_дома(дом, боёв):
        отчёт["сигналов"] += 1
        нити = нити_боевые(дом) if с.get("боевые") else нити_тестов(дом, с["файлы"])
        if not нити:
            отчёт["пусто"] += 1
            continue
        и = усилить(дом, нити, с["исход"], с["улика"], с["почему"])
        отчёт["обновлено"] += и["обновлено"]
        отчёт["пропущено"] += и["пропущено"]
        отчёт["отказов"] += 1 if и["отказ"] else 0
        отчёт["строки"].extend(и["строки"])
    отчёт["секунд"] = round(time.perf_counter() - тик, 2)
    return отчёт


def канарейка_дрейфа(дом: Path | str | None = None) -> dict:
    """Дрейф ловится: веса обязаны сходиться с журналом, держать границы,
    а мёртвые нити (без улик) — стоять ровно на базе 1.0."""
    дом = Path(дом) if дом else КОРЕНЬ
    причины: list[str] = []
    проекция = пересчитать_веса(дом)
    файл = _папка(дом) / "веса.json"
    если_есть = веса(дом)
    for ключ, значение in если_есть.items():
        ожидание = проекция.get(ключ, 1.0)
        if abs(значение - ожидание) > 1e-6:
            причины.append(f"дрейф: {ключ} = {значение}, журнал говорит {ожидание}")
        if not (ПОЛ_ВЕСА <= значение <= ПОТОЛОК_ВЕСА):
            причины.append(f"за границей [{ПОЛ_ВЕСА}, {ПОТОЛОК_ВЕСА}]: {ключ} = {значение}")
    мёртвые = [к for к in если_есть if к not in проекция]
    if мёртвые and not файл.exists():
        причины.append(f"мёртвых нитей {len(мёртвые)} без журнала")
    if проекция and not файл.exists():
        причины.append("веса.json пропал — проекция есть, файла нет")
    return {"вердикт": "чисто" if not причины else "дрейф",
            "нитей": len(если_есть), "с_уликами": len(проекция),
            "мёртвых": len(мёртвые), "причины": причины[:5]}

# ── Обход сети (Волна 7 плана): сеть строится и обходится в CI ──────────────
#
# Обход — не прогулка ради прогулки: КАЖДЫЙ узел дома предъявляется своей же
# сети как задача («всякий узел опознаётся своей сетью»). Шар обхода — доля
# узлов, которую считает ОДИН раннер; свод складывает шары. Так же считает и
# дом (шары процессами), и CI (шары раннерами) — мера одна: машинное время
# против календарного.

ПОРОГ_ОБХОДА = 0.8             # доля узлов, что обязаны опознать себя
ШАРОВ_ОБХОДА = 6               # шары по умолчанию (в CI — столько же раннеров)


def _запрос_узла(ид: str) -> str:
    """Имя узла как задача: «механизм:орган_чтение.py» → «орган чтение»."""
    _, _, имя = ид.partition(":")
    имя = имя.rsplit(".py", 1)[0]
    return имя.replace("_", " ").replace("-", " ").strip()


def шар_обхода(арг: dict) -> dict:
    """Топ-уровневая функция шара (годится и процессу, и раннеру CI).

    Читает дом, берёт СВОИ узлы и предъявляет каждый сети. Возвращает улику:
    сколько узлов опознано, сколько промахов и сколько секунд ушло у шара."""
    дом = Path(арг["дом"])
    иды = list(арг["иды"])
    повторов = max(1, int(арг.get("повторов") or 1))
    тик = time.perf_counter()
    узлы, рёбра = _загрузить_сеть(дом)
    self_hit, без_улик, ответили, промахи = 0, 0, 0, []
    нитей = {f"{р['от']}→{р['к']}" for р in рёбра}
    пройдено = set()
    for _ in range(повторов):              # повторы — чтобы дрожь не судила меру
      for ид in иды:
        if ид not in узлы:                      # узел исчез — честно в промахи
            if len(промахи) < 5:
                промахи.append({"узел": ид, "выбран": "", "счёт": 0.0})
            continue
        заявка = _запрос_узла(ид)
        токены = _токены(заявка)
        лучший, счёт, улики = _лучший_узел(узлы, токены, заявка=заявка,
                                           род_запроса=ид.split(":")[0])
        ответили += int(bool(лучший))
        без_улик += int(not улики)
        # обход по нитям узла: каждая нить шара отмечена пройденной
        for р in рёбра:
            if р["от"] == ид:
                пройдено.add(f"{р['от']}→{р['к']}")
        if лучший == ид:
            self_hit += 1
        elif len(промахи) < 5:
            промахи.append({"узел": ид, "выбран": лучший, "счёт": round(счёт, 2)})
    self_hit, без_улик, ответили = self_hit // повторов, без_улик // повторов, ответили // повторов
    return {"шара": арг.get("шара", 0), "запросов": len(иды), "повторов": повторов,
            "self_hit": self_hit,
            "без_улик": без_улик, "ответили": ответили, "промахи": промахи,
            "узлов": len(узлы), "рёбер": len(рёбра),
            "нитей_пройдено": len(пройдено), "нитей": len(нитей),
            "cpu": os.cpu_count() or 1,
            "секунд": round(time.perf_counter() - тик, 3)}


def _причины_обхода(запросов: int, ответили: int, пройдено: int,
                   нитей: int) -> list[str]:
    """Правило вердикта в одном месте: обход либо полон, либо названа причина.

    Самопознание узлов (узел в ответе на своё имя) — НЕ приговор обходу:
    это качество имён дома, оно живёт долгом в артефакте."""
    причины = []
    if запросов == 0:
        причины.append("сеть пуста: предъявлять нечего")
    if ответили < запросов:
        причины.append(f"без ответа {запросов - ответили} узлов")
    if нитей and пройдено < нитей:
        причины.append(f"не пройдено нитей {нитей - пройдено} из {нитей}")
    return причины


def _шары_узлов(узлы: dict, шаров: int, рёбра: list | None = None) -> list[dict]:
    """Доли узлов по ИЗМЕРЕННОЙ мере, а не по счёту.

    Грабли 01.10 (CI): доли делились по счёту (`иды[i::шаров]`), а вес узла
    разный — шар, которому достались тяжёлые узлы, жил дольше всех, и «обход
    ≥3×» решала дрожь (2,81× … 3,48× на одном и том же коде). Мера веса —
    исходящие нити узла плюс единица; тяжёлые узлы кладём первыми, каждый —
    в самую лёгкую долю (длиннейшая работа первой). Порядок и покрытие целы.
    """
    иды = sorted(узлы)
    шаров = max(1, int(шаров))
    вес = {и: 1.0 for и in иды}
    for р in (рёбра or []):
        if р.get("от") in вес:
            вес[р["от"]] += 1.0
    куски: list[list[str]] = [[] for _ in range(шаров)]
    груз = [0.0] * шаров
    for и in sorted(иды, key=lambda у: (-вес[у], у)):
        лёгкая = min(range(шаров), key=lambda i: (груз[i], i))
        куски[лёгкая].append(и)
        груз[лёгкая] += вес[и]
    return [{"дом": None, "шара": i + 1, "иды": sorted(к)}
            for i, к in enumerate(куски) if к]


def обход(дом: Path | str | None = None, шаров: int = ШАРОВ_ОБХОДА,
          работников: int = 1, писать: bool = False, повторов: int = 1) -> dict:
    """Обход сети: последовательно или шарами-процессами.

    Мера честная: «машинное_с» — работа всех шаров подряд, «секунд» — календарное
    время обхода. Работников больше одного — шары идут враз."""
    дом = Path(дом) if дом else КОРЕНЬ
    узлы, рёбра = _загрузить_сеть(дом)
    шары = _шары_узлов(узлы, шаров, рёбра)
    for ш in шары:
        ш["дом"] = str(дом)
        ш["повторов"] = max(1, int(повторов))
    тик = time.perf_counter()
    if работников > 1 and len(шары) > 1:
        with ProcessPoolExecutor(max_workers=min(работников, len(шары))) as пул:
            итоги = list(пул.map(шар_обхода, шары))
    else:
        итоги = [шар_обхода(ш) for ш in шары]
    секунд = round(time.perf_counter() - тик, 3)
    запросов = sum(и["запросов"] for и in итоги)
    self_hit = sum(и["self_hit"] for и in итоги)
    без_улик = sum(и["без_улик"] for и in итоги)
    ответили = sum(и["ответили"] for и in итоги)
    машинное = round(sum(и["секунд"] for и in итоги), 3)
    промахи = [п for и in итоги for п in и["промахи"]][:5]
    нитей = max((и["нитей"] for и in итоги), default=0)
    пройдено = sum(и["нитей_пройдено"] for и in итоги)   # шары делят источники
    доля = round(ответили / запросов, 3) if запросов else 0.0
    самопознание = round(self_hit / запросов, 3) if запросов else 0.0
    причины = _причины_обхода(запросов, ответили, пройдено, нитей)
    вердикт = "сеть обходится" if not причины else "сеть не обходится: " + "; ".join(причины)
    итог = {"когда": datetime.now().isoformat(timespec="seconds"),
            "узлов": len(узлы), "запросов": запросов, "ответили": ответили,
            "доля": доля, "self_hit": self_hit, "самопознание": самопознание,
            "без_улик": без_улик, "нитей": нитей, "нитей_пройдено": пройдено,
            "шаров": len(шары), "работников": работников, "cpu": os.cpu_count() or 1,
            "секунд": секунд, "машинное_с": машинное,
            "ускорение": round(машинное / секунд, 2) if секунд else 0.0,
            "шары": итоги, "промахи": промахи, "причины": причины, "вердикт": вердикт}
    if писать:
        _атомарно(_папка(дом) / "обход.json",
                  json.dumps({к: итог[к] for к in
                              ("когда", "узлов", "запросов", "self_hit", "доля",
                               "шаров", "секунд", "машинное_с", "ускорение",
                               "вердикт")}, ensure_ascii=False, indent=1))
    return итог


def замер_обхода(дом: Path | str | None = None, шаров: int = ШАРОВ_ОБХОДА,
                работников: int = 4, повторов: int = 1) -> dict:
    """Два замера одного труда на ОДНОЙ машине: подряд и враз.

    Это второе доказательство приёмки: «параллельный обход ≥3×» верно и внутри
    одного раннера (враз — шары процессами), и на многих раннерах (шары — свои
    раннеры). Результат обоих обязан совпасть: ускорение не смеет менять ответ."""
    дом = Path(дом) if дом else КОРЕНЬ
    повторов = max(1, int(повторов))
    подряд = обход(дом, шаров=1, работников=1, повторов=повторов)
    враз = обход(дом, шаров=шаров, работников=работников, повторов=повторов)
    одинаково = (подряд["self_hit"] == враз["self_hit"]
                 and подряд["ответили"] == враз["ответили"]
                 and подряд["нитей_пройдено"] == враз["нитей_пройдено"])
    секунд_подряд = max(подряд["секунд"], 0.001)
    итог = {"когда": datetime.now().isoformat(timespec="seconds"),
            "узлов": подряд["узлов"], "шаров": враз["шаров"], "повторов": повторов,
            "работников": min(работников, враз["шаров"]), "cpu": подряд["cpu"],
            "последовательно_с": подряд["секунд"], "враз_с": враз["секунд"],
            "ускорение_на_раннере": round(секунд_подряд / max(враз["секунд"], 0.001), 2),
            "ответили": {"подряд": подряд["ответили"], "враз": враз["ответили"]},
            "self_hit": {"подряд": подряд["self_hit"], "враз": враз["self_hit"]},
            "нитей_пройдено": {"подряд": подряд["нитей_пройдено"],
                               "враз": враз["нитей_пройдено"]},
            "результат_совпал": одинаково}
    return итог


def свод_обхода(папка: Path | str, порог_ускорения: float = 3.0) -> dict:
    """Свод шар-артефактов CI: машинное время против календарного.

    Каждый раннер мерил СВОЙ шар сам; свод складывает машинное (Σ) и берёт
    календарное как самый долгий шар (шары шли враз, на разных раннерах)."""
    папка = Path(папка)
    шары, замер = [], None
    for ф in sorted(папка.rglob("*.json")):
        try:
            д = json.loads(ф.read_text(encoding="utf-8"))
        except Exception:                       # noqa: BLE001 — чужие артефакты не наши
            continue
        if not isinstance(д, dict):
            continue
        if "ускорение_на_раннере" in д:
            замер = д
        elif "шара" in д and "self_hit" in д:
            шары.append(д)
    if not шары:
        return {"вердикт": "нет шар-артефактов", "ускорение": 0.0, "шаров": 0}
    запросов = sum(ш["запросов"] for ш in шары)
    self_hit = sum(ш["self_hit"] for ш in шары)
    ответили = sum(ш.get("ответили", 0) for ш in шары)
    машинное = round(sum(ш["секунд"] for ш in шары), 3)
    календарное = round(max(ш["секунд"] for ш in шары), 3)
    ускорение = round(машинное / календарное, 2) if календарное else 0.0
    доля = round(ответили / запросов, 3) if запросов else 0.0
    нитей = max((ш.get("нитей", 0) for ш in шары), default=0)
    пройдено = sum(ш.get("нитей_пройдено", 0) for ш in шары)   # шары делят источники
    на_раннере = round(float((замер or {}).get("ускорение_на_раннере") or 0.0), 2)
    лучшее = max(ускорение, на_раннере)
    причины = _причины_обхода(запросов, ответили, пройдено, нитей)
    if лучшее < порог_ускорения:
        причины.append(f"лучшее ускорение {лучшее}× < {порог_ускорения}× "
                        f"(раннеры {ускорение}×, враз {на_раннере}×)")
    return {"когда": datetime.now().isoformat(timespec="seconds"),
            "шаров": len(шары), "запросов": запросов, "ответили": ответили,
            "доля": доля, "self_hit": self_hit,
            "самопознание": round(self_hit / запросов, 3) if запросов else 0.0,
            "нитей": нитей, "нитей_пройдено": пройдено,
            "машинное_с": машинное, "календарное_с": календарное,
            "ускорение": ускорение, "ускорение_на_раннере": на_раннере,
            "ускорение_лучшее": лучшее, "порог_ускорения": порог_ускорения,
            "шар_секунды": [ш["секунд"] for ш in шары],
            "замер_на_раннере": замер, "причины": причины,
            "вердикт": "сеть обходится" if not причины else "сеть не обходится"}


