def _отпечаток(текст: bytes) -> str:
    """Отпечаток узла: правка содержимого видна — иначе сеть живёт ложью."""
    return hashlib.sha1(текст).hexdigest()[:12]


def _папка(дом: Path) -> Path:
    п = Path(дом).joinpath(*ПАПКА)
    п.mkdir(parents=True, exist_ok=True)
    return п


