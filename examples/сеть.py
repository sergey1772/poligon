БЮДЖЕТ_СЕТИ_БАЙТ = 5 * 1024 * 1024      # приёмка плана: производное сети ≤5 МБ
ПОРОГ_МЁРТВЫХ = 0.05                     # приёмка плана: мёртвых рёбер <5 %


def _степени(рёбра: list) -> dict[str, int]:
    """Сколько нитей держит узел: тупик — одна, сирота — ни одной."""
    с: dict[str, int] = {}
    for р in рёбра:
        с[р["от"]] = с.get(р["от"], 0) + 1
        с[р["к"]] = с.get(р["к"], 0) + 1
    return с


def _байты_сети(дом: Path) -> int:
    return sum(ф.stat().st_size for ф in _папка(дом).glob("*")
               if ф.is_file() and not ф.name.endswith(".tmp"))


def _доля_выбора(узлы: dict) -> tuple[int, int, list]:
    """hit@1 по типовым задачам: выбор идёт по узлам, нити двигают только шаги."""
    совпало, промахи = 0, []
    for задача, ждём in ТИПОВЫЕ:
        токены = _токены(задача)
        лучший, _, _ = _лучший_узел(узлы, токены)
        совпало += int(лучший == ждём)
        if лучший != ждём:
            промахи.append({"задача": задача, "ждём": ждём, "выбран": лучший})
    return совпало, len(ТИПОВЫЕ), промахи


def _строк_журнала(дом: Path) -> int:
    ф = _журнал_весов(дом)
    if not ф.exists():
        return 0
    return sum(1 for с in ф.read_text(encoding="utf-8").splitlines() if с.strip())


def _победители(узлы: dict) -> set[str]:
    """Кто выигрывает типовые задачи: сирота-победитель держится — иначе выбор падает."""
    с: set[str] = set()
    for задача, _ in ТИПОВЫЕ:
        лучший, _, _ = _лучший_узел(узлы, _токены(задача))
        if лучший:
            с.add(лучший)
    return с


def прунить(дом: Path | str | None = None, записать: bool = True) -> dict:
    """Сон сети: ядро и спайки остаются, мёртвые нити и сироты — в рецензию.

    Прунинг — по опыту (нить с весом на полу отвергнута падениями) и по
    структуре (узел без единой нити не может стать ходом маршрута). Спайк —
    изолированная пара узлов, которую опыт ещё не подтвердил: хранится, но
    отдельно от ядра. Сон пишет сжатую сеть и отчёт; узлы, рёбра и журнал
    весов не трогает — они принадлежат сборке и опыту, а не сну.
    """
    дом = Path(дом) if дом else КОРЕНЬ
    тик = time.perf_counter()
    узлы, рёбра = _загрузить_сеть(дом)
    веса_т = веса(дом)
    степень = _степени(рёбра)
    ядро, спайки, мёртвые = [], [], []
    for р in рёбра:
        ключ = _ключ_нити(р)
        вес = float(веса_т.get(ключ, 1.0))
        if р["от"] not in узлы or р["к"] not in узлы:
            мёртвые.append({**р, "вес": вес,
                            "почему": "узел исчез из дома — нить в пустоту"})
        elif вес <= ПОЛ_ВЕСА:
            мёртвые.append({**р, "вес": вес,
                            "почему": f"опыт отверг: вес {вес:.2f} ≤ пол {ПОЛ_ВЕСА}"})
        elif (степень.get(р["от"], 0) <= 1 and степень.get(р["к"], 0) <= 1
              and ключ not in веса_т):
            спайки.append({**р, "вес": вес})
        else:
            ядро.append({**р, "вес": вес})
    сироты = sorted(и for и in узлы if степень.get(и, 0) == 0)
    выигравшие = _победители(узлы)
    держатся = [и for и in сироты if и in выигравшие]      # без них выбор падает
    приглушены = [и for и in сироты if и not in выигравшие]
    узлы_сжатые = {и: у for и, у in узлы.items() if и not in set(приглушены)}
    совпало_до, всего, промахи_до = _доля_выбора(узлы)
    совпало_после, _, промахи_после = _доля_выбора(узлы_сжатые)
    hit_до = round(совпало_до / всего, 3) if всего else 0.0
    hit_после = round(совпало_после / всего, 3) if всего else 0.0
    доля_мёртвых = round(len(мёртвые) / len(рёбра), 4) if рёбра else 0.0
    строк, нитей_в_журнале = _строк_журнала(дом), len(веса_т)
    п = _папка(дом)
    if записать:                                   # сжатая сеть — до замера бюджета
        _атомарно(п / "ядро.jsonl", "".join(
            json.dumps(р, ensure_ascii=False) + "\n" for р in ядро))
        _атомарно(п / "спайки.jsonl", "".join(
            json.dumps(р, ensure_ascii=False) + "\n" for р in спайки))
        _атомарно(п / "рецензия_сон_сети.jsonl", "".join(
            json.dumps({"род": "сирота", "ид": и, "судьба": "приглушена",
                        "имя": узлы[и].get("имя", ""),
                        "состояние": узлы[и].get("состояние", ""),
                        "почему": "нет ни одной нити — узел не может стать ходом"},
                       ensure_ascii=False) + "\n" for и in приглушены)
            + "".join(json.dumps({"род": "сирота", "ид": и, "судьба": "держится",
                                  "имя": узлы[и].get("имя", ""),
                                  "состояние": узлы[и].get("состояние", ""),
                                  "почему": "нет нитей, но без неё падает выбор — "
                                            "сначала связать, потом глушить"},
                                 ensure_ascii=False) + "\n" for и in держатся)
            + "".join(json.dumps({"род": "мёртвая нить",
                                  "нить": _ключ_нити(р),
                                  "почему": р["почему"]}, ensure_ascii=False) + "\n"
                      for р in мёртвые))
    байт = _байты_сети(дом)
    улики: list[str] = []
    if hit_после < hit_до:
        улики.append("hit@1 упал после сжатия: сирота держит выбор — сон тревожный")
    if доля_мёртвых >= ПОРОГ_МЁРТВЫХ and мёртвые:
        улики.append(f"мёртвых рёбер {доля_мёртвых * 100:.1f} % ≥ "
                     f"{ПОРОГ_МЁРТВЫХ * 100:.0f} % — все уходят в рецензию")
    if сироты:
        улики.append(f"сирот {len(сироты)}: {len(приглушены)} в рецензию, "
                     f"{len(держатся)} держатся (без них падает выбор)")
    if байт > БЮДЖЕТ_СЕТИ_БАЙТ:
        улики.append(f"сеть {байт} Б больше бюджета {БЮДЖЕТ_СЕТИ_БАЙТ} Б")
    тревог = (hit_после < hit_до) or (байт > БЮДЖЕТ_СЕТИ_БАЙТ)
    отчёт = {
        "когда": datetime.now().isoformat(timespec="seconds"),
        "секунд": round(time.perf_counter() - тик, 2),
        "узлов": len(узлы), "рёбер": len(рёбра),
        "ядро": len(ядро), "спайки": len(спайки), "мёртвых": len(мёртвые),
        "мёртвых_доля": доля_мёртвых, "сирот": len(сироты),
        "сирот_приглушено": len(приглушены), "сирот_держится": len(держатся),
        "сироты_держатся": держатся[:5],
        "hit@1_до": hit_до, "hit@1_после": hit_после,
        "промахи_до": промахи_до[:5], "промахи_после": промахи_после[:5],
        "байт": байт, "бюджет_байт": БЮДЖЕТ_СЕТИ_БАЙТ,
        "бюджет_доля": round(байт / БЮДЖЕТ_СЕТИ_БАЙТ, 4),
        "журнал": {"строк": строк, "нитей": нитей_в_журнале,
                   "сжатие": round(строк / нитей_в_журнале, 2) if нитей_в_журнале else 0.0},
        "сжатая_сеть": {"нитей": len(ядро) + len(спайки),
                        "узлов": len(узлы) - len(приглушены)},
        "вердикт": "тревожный сон" if тревог else "спокойный сон",
        "улики": улики,
    }
    if записать:
        _атомарно(п / "сон_сети.json", json.dumps(отчёт, ensure_ascii=False, indent=1))
    return отчёт


def главное(argv: list[str] | None = None) -> int:
    арг = argv if argv is not None else sys.argv[1:]
    дом = КОРЕНЬ
    for к in ("--дом", "--house"):
        if к in арг:
            и = арг.index(к)
            if и + 1 < len(арг):
                дом = Path(арг[и + 1]).resolve()
    if "--собрать" in арг or "--build" in арг:
        с = собрать(дом)
        print(f"СЕТЬ: узлов {с['узлов']} · рёбер {с['рёбер']} · "
              f"циклов {с['циклов']} · висячих {с['висячих']} · {с['секунд']}с")
        for род, н in с["по_родам_узлов"].items():
            if н:
                print(f"  узлы {род}: {н}")
        for род, н in с["по_родам_рёбер"].items():
            if н:
                print(f"  нити {род}: {н}")
        return 0
    if "--маршрут" in арг or "--route" in арг:
        к = "--маршрут" if "--маршрут" in арг else "--route"
        и = арг.index(к)
        задача = арг[и + 1] if и + 1 < len(арг) else ""
        м = маршрут(задача, дом)
        print(f"РАЗВИЛКА: «{задача}» → {м['выбран']}  ({м['секунд']}с)")
        print(f"  причина: {м['причина']}")
        for ш in м["шаги"][1:]:
            print(f"  → {ш['узел']}: {ш['почему']}")
        return 0 if м["выбран"] else 1
    if "--гебб" in арг or "--hebb" in арг:
        о = усилить_по_дому(дом)
        к = канарейка_дрейфа(дом)
        print(f"ГЕББ: сигналов {о['сигналов']} · обновлено нитей {о['обновлено']} · "
              f"пропущено {о['пропущено']} · пусто {о['пусто']} · {о['секунд']}с")
        for д in о["строки"][:8]:
            print(f"  {д['дельта']:+.2f} {д['нить']}  ← {д['почему']}")
        print(f"КАНАРЕЙКА: {к['вердикт']} · нитей с уликами {к['с_уликами']}"
              + ("" if к["вердикт"] == "чисто" else f" · {к['причины'][:1]}"))
        return 0 if к["вердикт"] == "чисто" else 1
    if "--канарейка" in арг or "--canary" in арг:
        к = канарейка_дрейфа(дом)
        print(f"КАНАРЕЙКА ДРЕЙФА: {к['вердикт']} · нитей {к['нитей']} · "
              f"с уликами {к['с_уликами']} · мёртвых {к['мёртвых']}")
        for п in к["причины"]:
            print(f"  ⚠ {п}")
        return 0 if к["вердикт"] == "чисто" else 1
    if "--веса" in арг or "--weights" in арг:
        в = веса(дом)
        топ = sorted(в.items(), key=lambda п: -п[1])[:10]
        print(f"ВЕСА: нитей {len(в)} · с уликами {len(пересчитать_веса(дом))}")
        for к, з in топ:
            print(f"  {з:5.2f}  {к}")
        return 0
    if "--развилки" in арг or "--forks" in арг:
        р = развилки(дом)
        print(f"РАЗВИЛКИ: типовых {р['всего']} · совпало {р['совпало']} · "
              f"доля {р['доля']} · {р['секунд']}с")
        for пр in р["промахи"]:
            print(f"  ✗ «{пр['задача']}»: ждём {пр['ждём']}, выбран {пр['выбран']}")
        return 0 if р["доля"] >= 0.8 else 1
    if "--цемент" in арг or "--cement" in арг:
        к = "--цемент" if "--цемент" in арг else "--cement"
        и = арг.index(к)
        задача = арг[и + 1] if и + 1 < len(арг) else ""
        улика = ""
        if "--улика" in арг:
            ю = арг.index("--улика")
            улика = арг[ю + 1] if ю + 1 < len(арг) else ""
        ц = зацементировать(задача, дом, улика)
        if not ц["цемент"]:
            print(f"ЦЕМЕНТ: нет — {ц['почему']}")
            return 1
        print(f"ЦЕМЕНТ: «{задача}» → {ц['путь'][0]} · свидетелей {ц['свидетелей']}"
              f" · улика: {ц['улика']}")
        return 0
    if "--миелин" in арг or "--myelin" in арг:
        к = "--миелин" if "--миелин" in арг else "--myelin"
        и = арг.index(к)
        задача = арг[и + 1] if и + 1 < len(арг) else ""
        м = миелин(задача, дом)
        print(f"МИЕЛИН [{м['источник']}]: «{задача}» → {м['выбран']} ({м['секунд']}с)")
        print(f"  улика: {м['улика']}")
        for ш in м["шаги"][1:3]:
            print(f"  → {ш['узел']}: {ш['почему']}")
        return 0 if м["выбран"] else 1
    if "--маршруты" in арг or "--myelins" in арг:
        м = маршруты(дом)
        print(f"МАРШРУТЫ: путей {м['путей']} · свежих {м['свежих']} · "
              f"сошло {len(м['сошли'])}")
        for сш in м["сошли"][:5]:
            print(f"  ⚠ «{сш['задача']}»: {сш['почему']}")
        return 0
    if "--обход" in арг or "--walk" in арг:
        # Волна 7: обход сети (дом считает сам, шарами процессов)
        работников = 1
        if "--параллельно" in арг:
            и = арг.index("--параллельно")
            работников = int(арг[и + 1]) if и + 1 < len(арг) else 4
        шаров = ШАРОВ_ОБХОДА
        if "--шаров" in арг:
            и = арг.index("--шаров")
            шаров = int(арг[и + 1]) if и + 1 < len(арг) else шаров
        о = обход(дом, шаров=шаров, работников=работников, писать=True)
        if "--json" in арг:
            print(json.dumps(о, ensure_ascii=False))
        else:
            print(f"ОБХОД СЕТИ: узлов {о['узлов']} · ответили {о['ответили']}/{о['запросов']}"
                  f" ({о['доля']:.0%}) · нитей {о['нитей_пройдено']}/{о['нитей']}"
                  f" · самопознание {о['самопознание']:.0%} · без улик {о['без_улик']}"
                  f" · шаров {о['шаров']}")
            print(f"  машинное {о['машинное_с']}с · календарное {о['секунд']}с · "
                  f"ускорение {о['ускорение']}× · cpu {о['cpu']} · вердикт: {о['вердикт']}")
            for пр in о["промахи"][:5]:
                print(f"  ✗ {пр['узел']}: выбран {пр['выбран'] or '—'}")
        return 0 if о["вердикт"] == "сеть обходится" else 1
    if "--замер-обхода" in арг or "--walk-measure" in арг:
        # Волна 7: два замера одного труда на ОДНОЙ машине: подряд и враз
        з = замер_обхода(дом)
        текст = json.dumps(з, ensure_ascii=False, indent=1)
        if "--артефакт" in арг:
            и = арг.index("--артефакт")
            if и + 1 < len(арг):
                Path(арг[и + 1]).write_text(текст, encoding="utf-8")
        if "--json" in арг:
            print(json.dumps(з, ensure_ascii=False))
        else:
            print(f"ЗАМЕР ОБХОДА: узлов {з['узлов']} · cpu {з['cpu']} · "
                  f"шаров {з['шаров']} · работников {з['работников']}")
            print(f"  подряд {з['последовательно_с']}с · враз {з['враз_с']}с · "
                  f"ускорение {з['ускорение_на_раннере']}× · "
                  f"результат совпал: {'да' if з['результат_совпал'] else 'НЕТ'}")
        return 0 if з["результат_совпал"] else 1
    if "--шара-обхода" in арг or "--walk-shard" in арг:
        # Волна 7: один раннер CI считает СВОЮ долю узлов и отдаёт улику файлом
        к = "--шара-обхода" if "--шара-обхода" in арг else "--walk-shard"
        и = арг.index(к)
        пара = арг[и + 1] if и + 1 < len(арг) else "1/1"
        k, _, всего = пара.partition("/")
        шаров = max(1, int(всего or 1))
        узлы, рёбра = _загрузить_сеть(дом)
        шары = _шары_узлов(узлы, шаров, рёбра)
        мой = next((ш for ш in шары if ш["шара"] == int(k)), None)
        if мой is None:
            print(f"ШАРА {пара}: нет такой доли")
            return 1
        мой["дом"] = str(дом)
        if "--повторов" in арг:
            и3 = арг.index("--повторов")
            мой["повторов"] = max(1, int(арг[и3 + 1])) if и3 + 1 < len(арг) else 1
        р = шар_обхода(мой)
        текст = json.dumps(р, ensure_ascii=False, indent=1)
        if "--артефакт" in арг:
            и2 = арг.index("--артефакт")
            if и2 + 1 < len(арг):
                Path(арг[и2 + 1]).write_text(текст, encoding="utf-8")
        print(f"ШАРА ОБХОДА {k}/{шаров}: узлов {р['запросов']} · опознано {р['self_hit']}"
              f" · рёбер {р['рёбер']} · cpu {р['cpu']} · повторов {р.get('повторов', 1)}"
              f" · {р['секунд']}с")
        return 0
    if "--свод-обхода" in арг or "--walk-summary" in арг:
        к = "--свод-обхода" if "--свод-обхода" in арг else "--walk-summary"
        и = арг.index(к)
        папка = Path(арг[и + 1]) if и + 1 < len(арг) else Path("artifacts")
        с = свод_обхода(папка)
        текст = json.dumps(с, ensure_ascii=False, indent=1)
        if "--артефакт" in арг:
            и2 = арг.index("--артефакт")
            if и2 + 1 < len(арг):
                Path(арг[и2 + 1]).write_text(текст, encoding="utf-8")
        if "--json" in арг:
            print(json.dumps(с, ensure_ascii=False))
        else:
            print(f"СВОД ОБХОДА: шаров {с['шаров']} · узлов {с['запросов']} · "
                  f"ответили {с['ответили']} ({с['доля']:.0%}) · "
                  f"самопознание {с['self_hit']} ({с['самопознание']:.0%})")
            print(f"  машинное {с['машинное_с']}с · календарное {с['календарное_с']}с · "
                  f"ускорение раннеры {с['ускорение']}× · враз {с['ускорение_на_раннере']}×"
                  f" · лучшее {с['ускорение_лучшее']}× (порог {с['порог_ускорения']}×)")
            print(f"  вердикт: {с['вердикт']}")
            for пр in с["причины"]:
                print(f"  ⚠ {пр}")
        return 0 if с["вердикт"] == "сеть обходится" else 1
    if "--сон" in арг or "--sleep" in арг:
        с = прунить(дом)
        print(f"СОН СЕТИ: ядро {с['ядро']} · спайки {с['спайки']} · "
              f"мёртвых {с['мёртвых']} ({с['мёртвых_доля'] * 100:.1f} %) · "
              f"сирот {с['сирот']} → рецензия")
        print(f"  hit@1: {с['hit@1_до']} → {с['hit@1_после']} · "
              f"размер {с['байт'] / 1048576:.2f} МБ / "
              f"{с['бюджет_байт'] // 1048576} МБ · журнал "
              f"{с['журнал']['строк']} строк → {с['журнал']['нитей']} нитей · "
              f"{с['секунд']}с · вердикт: {с['вердикт']}")
        for у in с["улики"][:5]:
            print(f"  ⚠ {у}")
        return 0 if с["вердикт"] == "спокойный сон" else 1
    if "--сводка" in арг or "--summary" in арг:
        с = сводка(дом)
        if "--json" in арг:
            print(json.dumps(с, ensure_ascii=False))
        else:
            print(f"СЕТЬ: узлов {с['узлов']} · рёбер {с['рёбер']} · "
                  f"циклов {с['циклов']} · висячих {с['висячих']} · "
                  f"здоровье {с['здоровье']} · собрана {с['когда']}")
        return 0 if с["висячих"] == 0 else 1
    print("сеть дома (О-18): --собрать | --сводка [--json] | --маршрут \"задача\" | "
          "--развилки | --гебб | --веса | --канарейка | --цемент \"задача\" "
          "[--улика \"…\"] | --миелин \"задача\" | --маршруты | --сон | "
          "--обход [--параллельно N] [--шаров N] | --замер-обхода [--артефакт ф] | "
          "--шара-обхода k/N [--артефакт ф] | "
          "--свод-обхода папка [--json] | --дом путь")
    return 2


if __name__ == "__main__":
    sys.exit(главное(sys.argv[1:]))
