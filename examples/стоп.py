"""
Стоп-контур (Статья 35): исполнение P0-механизма.

Законы, обеспеченные этим кодом:
    35.1 единый стоп: семья / личность / задача; срабатывание — одна команда.
    35.3 кнопка только Суверена: подпись агента отклоняется; предохранитель —
         автоматические пороги, работает без человека.
    35.4 журнал стопов append-only; стоп обратим, восстановление — явный шаг.
    45.2 автоматизм: работа личности и задачи проверяется можно() — механизм
         сам не даёт работать в паузе.
    У5  (такт 23, ShinkaEvolve): лимит по оценкам — «сколько замеров», а не
         «сколько итераций»; параметр лимитов «оценок».
"""

# MODE: product

from __future__ import annotations

import json
import os
from datetime import datetime
from pathlib import Path


class НарушениеЗакона(Exception):
    """Попытка действия, запрещённого Конституцией."""


class СтопКонтур:
    """Три уровня остановки: семья > личность > задача (35.2)."""

    def __init__(self: "СтопКонтур", личности: set[str] = (),
                 дом: Path | None = None):
        self.агенты = set(личности)          # реестр: чьи подписи — агентские
        self.дом = Path(дом) if дом else None    # v111: куда кричит боль
        self.пауза: set[tuple[str, str]] = set()
        self.журнал: list[dict] = []         # append-only (35.4)

    # ── служебное ───────────────────────────────────────────────────────────
    @staticmethod
    def _ключ(цель: str) -> tuple[str, str]:
        if ":" in цель:
            тип, имя = цель.split(":", 1)
            return (тип, имя)
        return (цель, "")

    def _печать(self, событие: str, цель: str, кто: str) -> dict:
        запись = {"событие": событие, "цель": цель, "кто": кто,
                  "когда": datetime.now().isoformat(timespec="seconds")}
        self.журнал.append(запись)
        return запись

    def _проверить_суверена(self, кто: str) -> None:
        if not кто or кто in self.агенты:
            raise НарушениеЗакона("кнопка только Суверена (35.3): подпись агента отклонена")

    # ── кнопка (только Суверен) ─────────────────────────────────────────────
    def _крик(self, событие: str, цель: str, кто: str) -> None:
        """Боль/лечение стопа — фактом в журнал дома (v111, Волна 4):
        остановка органа — боль дома; сигнал не ломает контур при отказе."""
        try:
            from факты import боль, залечить
            ключ = f"стоп:{цель}"
            if событие == "стоп":
                боль(f"остановлено: {цель} (кто: {кто})", кто="стоп",
                     дом=self.дом, ключ=ключ, улика="35.4 стоп-контур")
            else:
                залечить(ключ, чем=f"возобновлено: {цель} (кто: {кто})",
                         дом=self.дом, кто="стоп")
        except (ImportError, RuntimeError):
            pass

    def стоп(self, цель: str, кто: str) -> dict:
        """цель: «семья» | «личность:Имя» | «задача:ID»."""
        self._проверить_суверена(кто)
        self.пауза.add(self._ключ(цель))
        печать = self._печать("стоп", цель, кто)
        self._крик("стоп", цель, кто)
        return печать

    def возобновить(self, цель: str, кто: str) -> dict:
        """Восстановление — явный шаг, не побочный эффект (35.4)."""
        self._проверить_суверена(кто)
        self.пауза.discard(self._ключ(цель))
        печать = self._печать("возобновление", цель, кто)
        self._крик("возобновление", цель, кто)
        return печать

    # ── предохранитель (автоматический, без человека) ───────────────────────
    def предохранитель(self, личность: str, итераций: int, подряд_отказов: int,
                       израсходовано: float, лимиты: dict,
                       оценок: int = 0) -> bool:
        """Сработал, если хоть один порог пробит; ставит паузу сам (35.3).
        У5: бюджет может считаться в ОЦЕНКАХ (вызовах судьи/замера), а не
        в итерациях или минутах — цена попыток честнее."""
        пробито = (итераций > лимиты.get("итераций", 10 ** 9)
                   or подряд_отказов > лимиты.get("подряд_отказов", 10 ** 9)
                   or израсходовано > лимиты.get("бюджет", float("inf"))
                   or (оценок > лимиты["оценок"] if "оценок" in лимиты else False))
        if пробито:
            self.пауза.add(("личность", личность))
            self._печать("предохранитель", f"личность:{личность}", "предохранитель")
        return пробито

    # ── врата работы (механизм сам не пускает в паузу) ──────────────────────
    def можно(self, личность: str, задача: str | None = None) -> bool:
        if ("семья", "") in self.пауза:
            return False
        if ("личность", личность) in self.пауза:
            return False
        if задача and ("задача", задача) in self.пауза:
            return False
        return True

    # ── состояние между процессами (врата живых циклов) ─────────────────────
    def сохранить_состояние(self, путь: str | Path) -> None:
        p = Path(путь)
        tmp = p.with_suffix(p.suffix + ".tmp")   # ст. 53.2: атомарная запись
        tmp.write_text(json.dumps({"пауза": sorted(self.пауза),
                                   "журнал": self.журнал,
                                   "агенты": sorted(self.агенты)},
                                  ensure_ascii=False, indent=1), encoding="utf-8")
        os.replace(tmp, p)

    @classmethod
    def загрузить_состояние(cls, путь: str | Path) -> "СтопКонтур":
        к = cls()
        p = Path(путь)
        if p.exists():
            д = json.loads(p.read_text(encoding="utf-8"))
            к.пауза = {(т, и) for т, и in д.get("пауза", [])}
            к.журнал = д.get("журнал", [])
            к.агенты = set(д.get("агенты", []))   # кнопка только Суверена и после перезапуска (35.3)
        return к

    # ── журнал: добавление, не перезапись ───────────────────────────────────
    def сохранить(self, путь: str | Path) -> None:
        p = Path(путь)
        старое = json.loads(p.read_text(encoding="utf-8")) if p.exists() else []
        if self.журнал[:len(старое)] != старое:
            raise НарушениеЗакона("перезапись журнала стопов запрещена (35.4)")
        tmp = p.with_suffix(p.suffix + ".tmp")   # ст. 53.2: атомарная запись
        tmp.write_text(json.dumps(self.журнал, ensure_ascii=False, indent=1),
                       encoding="utf-8")
        os.replace(tmp, p)
