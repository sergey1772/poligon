"""Сторож песочницы (Х-21 · о-3, слово Суверена 30.09: «нужен сторож по всем
тайм-аутам песочницы и переполнения… нужно подстроиться под песочницу»).

Песочница — не железо, а сосед: она мерзнет, когда вызов велик, и
переполняется, когда мусор копится. Сторож держит три вещи:
  1) ЁМКОСТЬ — /tmp, память, вес дома (цель 90 МБ · потолок 128 МБ);
  2) ТАЙМ-АУТЫ — журнал вмерзаний (кто, сколько, предел) → БЮДЖЕТ ЧАСТИ;
  3) ПЕРЕПОЛНЕНИЕ — вердикт «тесно» и уборка своего мусора.

Бюджет части — МЕРА, а не константа: падает при вмерзаниях и тесноте,
возвращается к потолку, когда в окне свежести чисто. Так бой сам
подстраивается под песочницу, а не надеется на удачу.
"""

# MODE: product

from __future__ import annotations

import json
import re
import shutil
from datetime import datetime, timedelta
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ЖУРНАЛ = "00_START/сторож_песочницы.json"

ПРЕДЕЛ_ВЫЗОВА_С = 45      # ЖЁСТКО: ни один вызов не длится дольше
ПОТОЛОК_СУВЕРЕНА_С = 50    # слово Суверена: «тайм-аут более 50 — накажу»
БЮДЖЕТ_ПОТОЛОК_С = 45      # слово Суверена: фотон ≤45 с
БЮДЖЕТ_ПОЛ_С = 15          # ниже — смысл части теряется (запуски дороже работы)
ШАГ_ВНИЗ_С = 10            # каждое свежее вмерзание — минус шаг
СВЕЖЕСТЬ_Ч = 6             # окно, в котором вмерзания давят на бюджет
ТЕСНО_МБ = 300             # меньше свободного (в /tmp или в памяти) — «тесно»
ТЕСНЫЙ_БЮДЖЕТ_С = 25       # в тесноте дробить мельче
КВОТА_МБ = 128             # потолок веса дома
ЦЕЛЬ_МБ = 90               # рабочая цель веса дома


def _дом(дом: Path | None = None) -> Path:
    return Path(дом) if дом else КОРЕНЬ


def память_мб() -> int:
    """Свободная память песочницы (MemAvailable) — 0, если прочитать не вышло."""
    try:
        текст = Path("/proc/meminfo").read_text(encoding="utf-8")
        м = re.search(r"^MemAvailable:\s+(\d+) kB", текст, re.M)
        return round(int(м.group(1)) / 1024) if м else 0
    except Exception:
        return 0


def _вес_мб(путь: Path) -> float:
    вес = 0
    for ф in путь.rglob("*"):
        try:
            if ф.is_file():
                вес += ф.stat().st_size
        except OSError:
            continue
    return round(вес / 2 ** 20, 1)


def ёмкость(дом: Path | None = None) -> dict:
    """Что у песочницы есть: /tmp, память, вес дома — и тесно ли."""
    х = _дом(дом)
    try:
        свободно_мб = round(shutil.disk_usage("/tmp").free / 2 ** 20)
    except OSError:
        свободно_мб = 0
    память = память_мб()
    вес = _вес_мб(х) if х.exists() else 0.0
    причины = []
    if свободно_мб < ТЕСНО_МБ:
        причины.append(f"/tmp свободно {свободно_мб} МБ < {ТЕСНО_МБ}")
    if память and память < ТЕСНО_МБ:
        причины.append(f"память свободна {память} МБ < {ТЕСНО_МБ}")
    if вес > КВОТА_МБ:
        причины.append(f"вес дома {вес} МБ > квоты {КВОТА_МБ}")
    return {"свободно_мб": свободно_мб, "память_мб": память, "вес_дома_мб": вес,
            "тесно": bool(причины), "почему": "; ".join(причины) or "ёмко",
            "вердикт": "тесно" if причины else "ёмко"}


def журнал(дом: Path | None = None) -> dict:
    п = _дом(дом) / ЖУРНАЛ
    if п.exists():
        try:
            д = json.loads(п.read_text(encoding="utf-8"))
            д.setdefault("события", [])
            return д
        except Exception:
            pass
    return {"события": [], "бюджет_с": БЮДЖЕТ_ПОТОЛОК_С, "вмерзаний": 0}


def _сохранить(дом: Path | None, ж: dict) -> None:
    п = _дом(дом) / ЖУРНАЛ
    п.parent.mkdir(parents=True, exist_ok=True)
    ж["события"] = ж["события"][-50:]          # мера не пухнет
    ж["вмерзаний"] = len(ж["события"])
    ж["бюджет_с"] = _пересчитать(дом, ж)
    п.write_text(json.dumps(ж, ensure_ascii=False, indent=1), encoding="utf-8")


def свежие(дом: Path | None = None, часы: float = СВЕЖЕСТЬ_Ч) -> list[dict]:
    """Вмерзания в окне свежести: по КОНТЕНТУ (метка «когда»), не по mtime."""
    предел = datetime.now() - timedelta(hours=часы)
    итог = []
    for с in журнал(дом)["события"]:
        try:
            когда = datetime.fromisoformat(str(с.get("когда", "")))
        except ValueError:
            continue
        if когда >= предел:
            итог.append(с)
    return итог


def вмерзание(дом: Path | None, кто: str, сек: float = 0.0,
              предел: float = 0.0, вид: str = "часть") -> dict:
    """Записать вмерзание (тайм-аут песочницы) и пересчитать бюджет."""
    ж = журнал(дом)
    ж["события"].append({
        "когда": datetime.now().isoformat(timespec="seconds"),
        "кто": str(кто)[:80], "сек": round(float(сек), 1),
        "предел": round(float(предел), 1), "вид": str(вид)[:20]})
    _сохранить(дом, ж)
    return ж


def _пересчитать(дом: Path | None, ж: dict | None = None) -> int:
    ж = ж or журнал(дом)
    свежих = len(свежие(дом))
    бюджет = max(БЮДЖЕТ_ПОЛ_С, БЮДЖЕТ_ПОТОЛОК_С - ШАГ_ВНИЗ_С * свежих)
    if ёмкость(дом)["тесно"]:
        бюджет = min(бюджет, ТЕСНЫЙ_БЮДЖЕТ_С)
    return бюджет


def бюджет_части(дом: Path | None = None) -> int:
    """Сколько секунд работы класть в одну часть (вызов) прямо сейчас."""
    return _пересчитать(дом)


def вердикт(дом: Path | None = None) -> dict:
    """Полный доклад сторожа: ёмкость, свежие вмерзания, бюджет."""
    е = ёмкость(дом)
    св = свежие(дом)
    б = бюджет_части(дом)
    если_тесно = " · тесно, дробить мельче" if е["тесно"] else ""
    почему = (f"часть ≤{б}с (потолок {БЮДЖЕТ_ПОТОЛОК_С} − {ШАГ_ВНИЗ_С}×"
              f"{len(св)} свежих вмерзаний){если_тесно}")
    return {"ёмкость": е, "свежих_вмерзаний": len(св), "бюджет_с": б,
            "почему": почему, "вмерзаний": журнал(дом)["вмерзаний"],
            "вердикт": е["вердикт"] if not св else "вмерзало"}


СВОИ_ПРЕФИКСЫ = ("заход-", "дом-", "бой-", "замер-", "мз", "ск-", "бт_", "bt")


def уборка_своих(мин: float = 10.0, где: str = "/tmp") -> dict:
    """Осиротевшие временные папки дома (оборванный вызов не снёс за собой —
    так «песочница ложится»): сносим СВОИ префиксы старше `мин` минут.
    Чужое (платформенное) не трогаем никогда."""
    import time as _в
    убрано, освобождено, пропущено = 0, 0.0, 0
    предел = _в.time() - мин * 60
    for п in Path(где).iterdir():
        if not п.name.startswith(СВОИ_ПРЕФИКСЫ):
            continue
        try:
            if п.stat().st_mtime > предел:
                пропущено += 1          # свежая — возможно, чужой живой вызов
                continue
            вес = _вес_мб(п) if п.is_dir() else п.stat().st_size / 2 ** 20
            if п.is_dir():
                shutil.rmtree(п, ignore_errors=True)
            else:
                п.unlink(missing_ok=True)
            убрано += 1
            освобождено += вес
        except OSError:
            continue
    return {"убрано": убрано, "освобождено_мб": round(освобождено, 1),
            "свежих_пропущено": пропущено}


ПОРОГ_ГИТ_МБ = 40            # выше — история тяжелеет: упаковывается сама
ПОРОГ_ДОМА_МБ = 90           # цель Суверена: дом < 90 МБ (потолок 128)


def вес_гита(дом: Path | None = None) -> float:
    """Вес каталога .git в МБ (0.0 — если это не дом git)."""
    г = Path(дом or КОРЕНЬ) / ".git"
    if not г.exists():
        return 0.0
    сумма = 0
    for ф in г.rglob("*"):
        try:
            if ф.is_file():
                сумма += ф.stat().st_size
        except OSError:
            continue
    return round(сумма / (1024 * 1024), 1)


def подрезать(дом: Path | None = None) -> dict:
    """Самоподрезка веса: .git выше порога — упаковать историю (git gc).

    Живой разбор 01.10: дом весил 97,9 МБ (цель 90), .git — 62 МБ;
    упаковка вернула 36 МБ и вес 74,9 МБ. Производное тяжёлое не в git;
    история — улика, её НЕ переписываем: только упаковка.
    """
    д = Path(дом or КОРЕНЬ)
    было = вес_гита(д)
    if было == 0.0:
        return {"было": 0.0, "стало": 0.0, "подрезано": False,
                "почему": "не дом git — подрезать нечего"}
    if было <= ПОРОГ_ГИТ_МБ:
        return {"было": было, "стало": было, "подрезано": False,
                "почему": f".git {было} МБ ≤ порога {ПОРОГ_ГИТ_МБ} МБ"}
    import subprocess
    try:
        subprocess.run(["git", "-C", str(д), "gc", "--prune=now", "-q"],
                       capture_output=True, text=True, timeout=40)
    except Exception as е:                   # noqa: BLE001 — честный отказ
        return {"было": было, "стало": было, "подрезано": False,
                "почему": f"упаковка не удалась: {type(е).__name__}"}
    стало = вес_гита(д)
    return {"было": было, "стало": стало, "подрезано": True,
            "почему": f"история упакована: {было} → {стало} МБ"}


def главное(аргументы: list[str] | None = None) -> int:
    import sys
    арг = аргументы if аргументы is not None else sys.argv[1:]
    дом = Path(арг[0]).resolve() if арг and not арг[0].startswith("--") else КОРЕНЬ
    if "--подрезать" in арг:
        р = подрезать(дом)
        print(f"ПОДРЕЗКА: {р['почему']}")
        return 0 if р["подрезано"] or "≤ порога" in р["почему"] or "не дом" in р["почему"] else 1
    if "--бюджет" in арг:
        б = бюджет_части(дом)
        print(f"БЮДЖЕТ ЧАСТИ: {б}с · {вердикт(дом)['почему']}")
        return 0
    if "--учесть" in арг:
        и = арг.index("--учесть")
        кто = арг[и + 1] if и + 1 < len(арг) else "без имени"
        сек = float(арг[арг.index("--сек") + 1]) if "--сек" in арг else 0.0
        вмерзание(дом, кто, сек=сек, вид="рука")
        print(f"УЧТЕНО: {кто} {сек}с → бюджет {бюджет_части(дом)}с")
        return 0
    if "--убрать" in арг:
        р = уборка_своих()
        print(f"УБРАНО: {р['убрано']} своих временных папок, "
              f"освобождено {р['освобождено_мб']} МБ "
              f"(свежих пропущено {р['свежих_пропущено']})")
        return 0
    if "--события" in арг:
        ж = журнал(дом)
        print(f"СОБЫТИЙ: {ж['вмерзаний']} · свежих {len(свежие(дом))}")
        for с in ж["события"][-8:]:
            print(f"  {с['когда']} [{с['вид']}] {с['кто']} {с['сек']}с "
                  f"(предел {с['предел']}с)")
        return 0
    в = вердикт(дом)
    е = в["ёмкость"]
    print(f"СТОРОЖ: {в['вердикт'].upper()} · бюджет части {в['бюджет_с']}с · "
          f"вызов ≤{ПРЕДЕЛ_ВЫЗОВА_С}с (потолок Суверена {ПОТОЛОК_СУВЕРЕНА_С}) · "
          f"вмерзаний {в['вмерзаний']} (свежих {в['свежих_вмерзаний']})")
    print(f"  ёмкость: /tmp свободно {е['свободно_мб']} МБ · память "
          f"{е['память_мб']} МБ · вес дома {е['вес_дома_мб']} МБ "
          f"(цель {ЦЕЛЬ_МБ} · потолок {КВОТА_МБ})")
    if е["почему"] != "ёмко":
        print(f"  тесно: {е['почему']}")
    return 0 if not е["тесно"] else 1


if __name__ == "__main__":
    raise SystemExit(главное())
