#!/usr/bin/env python3
"""Тесты органа «Вердикт» (Статья 60): вердикт принадлежит голове.

Проверяем: отменённый прогон — не зелёный; успех на другой голове не
считается; провал после успеха на той же голове краснит; контур, который
не запускался, не зеленит; на главной ветке отмена запрещена (мировой опыт:
cancelled не публикует ни артефактов, ни результатов).
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import вердикт  # noqa: E402


def _п(name: str, ша: str, исход: str, номер: int, статус: str = "completed"):
    return {"name": name, "head_sha": ша, "conclusion": исход,
            "status": статус, "run_number": номер, "created_at": "2026-10-01T10:00:00Z"}


def test_отменённый_не_зелёный():
    """60.2: отмена не публикует результатов — это «нет вердикта», не успех."""
    в = вердикт.из_прогонов("a" * 8, [_п("ворота", "a" * 8, "cancelled", 1)])
    assert в["вердикты"]["ворота"] == "нет вердикта" and в["вердикт"] == "нет вердикта"


def test_успех_чужой_головы_не_считается():
    """60.1: вердикт принадлежит голове — успех на другой голове не вердикт."""
    в = вердикт.из_прогонов("a" * 8, [_п("ворота", "b" * 8, "success", 1)])
    assert в["вердикты"] == {} and в["вердикт"] == "нет прогонов"


def test_провал_после_успеха_краснит_голову():
    """60.5: судится последний завершённый прогон контура, а не удобный."""
    прогоны = [_п("ворота", "a" * 8, "success", 1), _п("ворота", "a" * 8, "failure", 2)]
    в = вердикт.из_прогонов("a" * 8, прогоны)
    assert в["вердикты"]["ворота"] == "красный" and в["вердикт"] == "красный"


def test_не_запускавшийся_контур_не_зеленит():
    """60.5: молчание контура — не зелёный: «не запускался» держит «нет вердикта»."""
    в = вердикт.из_прогонов("a" * 8, [_п("ворота", "a" * 8, "success", 1)],
                            контуры=("ворота", "poligon"))
    assert в["вердикты"]["poligon"] == "не запускался"
    assert в["вердикт"] == "нет вердикта"


def test_отмена_на_главной_запрещена(tmp_path):
    """60.3: безусловная отмена в контуре — нарушение; условная — порядок."""
    плохой = tmp_path / "плохой.yml"
    плохой.write_text("concurrency:\n  cancel-in-progress: true\n", encoding="utf-8")
    assert вердикт.отмена_на_главной_запрещена(плохой)
    дом = Path(__file__).parent.parent
    assert вердикт.отмена_на_главной_запрещена(дом / ".github/workflows/tests.yml") == []


def test_свод_видит_расхождение_голов():
    """60.4: дом и сервер на разных головах — дом судит копию (не зелёный)."""
    с = вердикт.свод(прогоны=[_п("ворота", "a" * 8, "success", 1)],
                     голова_сервера_ша="b" * 8)
    assert с["одна_голова"] is False and "копи" in с["причина"]
