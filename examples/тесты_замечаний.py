#!/usr/bin/env python3
"""Тесты органа «Замечания» (Статья 61).

Проверяем законы: без улики — отказ; замечено — записано (журнал переживает
битую строку и обрыв); повтор поднимает вес и на третьем замечании по ткани
требует обобщения (урок/статья); закрыть можно только внедрённое или отложенное
с причиной; висяк дольше 48 часов краснит; затишье — РОСТ, а не чистота.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import замечания as З  # noqa: E402


def _дом(tmp_path: Path) -> Path:
    (tmp_path / "42_УРОКИ").mkdir(parents=True, exist_ok=True)
    return tmp_path


def test_замечено_значит_записано(tmp_path):
    """61.2: замечание легло в журнал и получило лёгкий вес по лупе."""
    дом = _дом(tmp_path)
    з = З.заметить(дом, текст="счётчик молчит вторые сутки", ткань="молчание",
                   улика="00_START/сторож.json:строка 3", лупа="тишина")
    assert з["номер"] == 1 and з["статус"] == "замечено" and з["вес"] == 3
    assert len(З.прочитать(дом)) == 1
    assert (дом / "42_УРОКИ/замечания.md").exists()


def test_без_улики_отказ(tmp_path):
    """61.3: без улики это мнение, а не замечание."""
    дом = _дом(tmp_path)
    try:
        З.заметить(дом, текст="мне кажется, что-то не так", ткань="смута")
    except З.Замечание as е:
        assert "улик" in str(е)
    else:
        raise AssertionError("замечание без улики принято")
    assert З.прочитать(дом) == []


def test_пустое_и_чужая_лупа_отвергаются(tmp_path):
    """Пустой текст и лупа вне списка — честный отказ, а не молчаливая запись."""
    дом = _дом(tmp_path)
    for доводы in ({"текст": "", "улика": "м"}, {"текст": "т", "улика": "м",
                                                "лупа": "наитие"}):
        try:
            З.заметить(дом, **{"ткань": "т", **доводы})
        except З.Замечание:
            pass
        else:
            raise AssertionError(f"принято вопреки закону: {доводы}")


def test_повтор_тяжелеет_и_требует_обобщения(tmp_path):
    """61.5: третье замечание по ткани поднимает вес и требует урок/статью."""
    дом = _дом(tmp_path)
    в1 = З.заметить(дом, текст="а", ткань="фильтр путей", улика="m:1")["вес"]
    в2 = З.заметить(дом, текст="б", ткань="фильтр путей", улика="m:2")["вес"]
    з3 = З.заметить(дом, текст="в", ткань="фильтр путей", улика="m:3")
    assert (в1, в2, з3["вес"]) == (4, 5, 5) and з3["повтор"] == 3
    э = З.эскалации(дом)
    assert э and э[0]["ткань"] == "фильтр путей" and "урок" in э[0]["почему"]


def test_закрыть_без_действия_нельзя(tmp_path):
    """61.4: замечание без действия — украшение; закрытие до действия отказ."""
    дом = _дом(tmp_path)
    з = З.заметить(дом, текст="молчит", ткань="молчание", улика="m:1")
    try:
        З.закрыть(дом, номер=з["номер"])
    except З.Замечание as е:
        assert "украшение" in str(е)
    else:
        raise AssertionError("закрыто замечание без действия")
    З.внедрить(дом, номер=з["номер"], куда="клетка test_тишина")
    assert З.закрыть(дом, номер=з["номер"])["статус"] == "закрыто"


def test_отложить_можно_только_с_причиной(tmp_path):
    """61.6: склад — не свалка: отложенное обязано быть названо с причиной."""
    дом = _дом(tmp_path)
    з = З.заметить(дом, текст="лишний вес", ткань="вес", улика="m:1", лупа="лишнее")
    try:
        З.отложить(дом, номер=з["номер"], причина="  ")
    except З.Замечание as е:
        assert "причин" in str(е)
    else:
        raise AssertionError("отложено без причины")
    З.отложить(дом, номер=з["номер"], причина="ждём волну 8")
    assert З.закрыть(дом, номер=з["номер"])["статус"] == "закрыто"


def test_вид_действия_только_из_списка(tmp_path):
    """Действие обязано быть клеткой, уроком, статьёй или долгом."""
    дом = _дом(tmp_path)
    з = З.заметить(дом, текст="x", ткань="т", улика="m:1")
    try:
        З.назначить(дом, номер=з["номер"], действие="подумать", вид="настроение")
    except З.Замечание as е:
        assert "вне списка" in str(е)
    else:
        raise AssertionError("принят вид действия вне списка")


def test_висяк_краснит_и_затишье_ростит(tmp_path):
    """61.2/61.6: висяк >48ч — КРАСНЫЙ; затишье >7 сут — РОСТ, а не чистота."""
    дом = _дом(tmp_path)
    з = З.заметить(дом, текст="висит", ткань="висит", улика="m:1")
    п = дом / "42_УРОКИ/замечания.jsonl"
    старая = (datetime.now() - timedelta(hours=72)).isoformat(timespec="seconds")
    п.write_text(json.dumps(dict(з, когда=старая), ensure_ascii=False) + "\n",
                 encoding="utf-8")
    с = З.свод(дом)
    assert с["висяков"] == 1 and с["вердикт"] == "КРАСНЫЙ" and "украшение" in с["почему"]
    Ш, З_ = З.шаг_ритма(дом)
    assert Ш is False and "КРАСНЫЙ" in З_
    # затишье: замечание внедрено и было давно
    записи = З.прочитать(дом)
    for х in записи:
        х["статус"], х["куда"] = "внедрено", "клетка x"
        х["когда"] = (datetime.now() - timedelta(days=30)).isoformat(timespec="seconds")
    п.write_text("\n".join(json.dumps(х, ensure_ascii=False) for х in записи) + "\n",
                 encoding="utf-8")
    с2 = З.свод(дом)
    assert с2["вердикт"] == "РОСТ" and "затишь" in с2["почему"]


def test_битая_строка_не_роняет_журнал(tmp_path):
    """У-253: журнал читается, даже если строка испорчена; обрыв не теряет запись."""
    дом = _дом(tmp_path)
    З.заметить(дом, текст="живое", ткань="т", улика="m:1")
    п = дом / "42_УРОКИ/замечания.jsonl"
    п.write_text(п.read_text(encoding="utf-8") + "{битая строка\n", encoding="utf-8")
    assert len(З.прочитать(дом)) == 1
    з2 = З.заметить(дом, текст="второе", ткань="т2", улика="m:2")
    assert з2["номер"] == 2 and len(З.прочитать(дом)) == 2


def test_слово_суверена_тяжелее(tmp_path):
    """61.1: слово Суверена — замечание высшего веса (замечает человек)."""
    дом = _дом(tmp_path)
    а = З.заметить(дом, текст="а", ткань="т1", улика="m:1", лупа="лишнее")
    с = З.заметить(дом, текст="с", ткань="т2", улика="m:2", лупа="лишнее",
                   кто="Суверен", откуда="слово Суверена")
    assert с["вес"] > а["вес"] and с["откуда"] == "слово Суверена"


