#!/usr/bin/env python3
"""Журнал фактов дома — единая дверь измерений (уровень ФАКТ).

Дверь одна на дом: любой орган объявляет своё измерение фактом, а не
заводит собственный журнал и не обходит контур. Минимум честности:
задача, выбор, кто (пустое — брак, ValueError); выбор обязан лежать в
объявленном спектре «из» (маршрут вне спектра — отказ). Номер и момент
штампует дверь; запись атомарная (ст. 52.2) — старая + новая в tmp,
затем os.replace, читатель не видит рваной строки.

Выделено из контур.py (v108, Волна 1): двигатель и контур не должны
импортировать друг друга — иначе граф зависимостей дома ловит петлю,
а журнал первичен (event sourcing: журнал — источник истины, сводки —
производные).
"""
from __future__ import annotations

import hashlib
import json
import math
import os
from datetime import datetime
from pathlib import Path

# Проба не пишет в боевой журнал (Гарант 114, честная находка v110):
# тесты зовут боевые CLI — измерения боевого дома рождаются только делом.
ПРОБА_МАРКЕР = "PYTEST_CURRENT_TEST"

КОРЕНЬ = Path(__file__).resolve().parent.parent
ФАКТЫ_ФАЙЛ = "32_SELFUPGRADE/факты.jsonl"
СВОДКА_ФАЙЛ = "32_SELFUPGRADE/сводка_фактов.md"
БАЗА_ЦЕПИ = b"FACT-JOURNAL-1"       # корень цепи: до первого факта
БАЗА_ХЭШ = hashlib.sha256(БАЗА_ЦЕПИ).hexdigest()   # печать пустого журнала


def _сырые_строки(дом: Path) -> list[str]:
    """Строки журнала как лежат (без пустых) — по ним идёт цепь."""
    путь = дом / ФАКТЫ_ФАЙЛ
    if not путь.exists():
        return []
    return [с for с in путь.read_text(encoding="utf-8").splitlines() if с.strip()]


def _хэши_префиксов(строки: list[str]) -> list[str]:
    """Хэш каждой накопленной истории: хэш(и) = sha256(корень + строки[:i+1]).
    Считается один раз проходом — цепь O(n)."""
    х = hashlib.sha256(БАЗА_ЦЕПИ)
    итог: list[str] = []
    for с in строки:
        х.update(с.encode("utf-8"))
        х.update(b"\n")
        итог.append(х.hexdigest())
    return итог


def _печать(запись: dict) -> str:
    """Печать записи: sha256 канонического вида без самого поля «печать»."""
    копия = {к: v for к, v in запись.items() if к != "печать"}
    тело = json.dumps(копия, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(тело.encode("utf-8")).hexdigest()[:16]



def _дозапись(путь: Path, строка: str) -> None:
    """Атомарная дозапись (ст. 52.2)."""
    путь.parent.mkdir(parents=True, exist_ok=True)
    старый = путь.read_text(encoding="utf-8") if путь.exists() else ""
    временный = путь.with_suffix(путь.suffix + ".tmp")
    временный.write_text(старый + строка, encoding="utf-8")
    os.replace(временный, путь)


def номер_факта(дом: Path | None = None) -> int:
    """Номер следующего факта: сколько фактов уже лежит в журнале + 1."""
    дом = Path(дом) if дом else КОРЕНЬ
    путь = дом / ФАКТЫ_ФАЙЛ
    if not путь.exists():
        return 1
    строки = [с for с in путь.read_text(encoding="utf-8").splitlines()
              if с.strip()]
    return len(строки) + 1


def записать_факт(дом: Path | None, факт: dict) -> dict:
    """Публичная дверь журнала: измерение становится фактом дома.
    Номер и момент штампует дверь; запись входит в цепь хэшей — несёт
    печать всей предыдущей истории (подмена прошлого ловится, v109)."""
    дом = Path(дом) if дом else КОРЕНЬ
    if os.environ.get(ПРОБА_МАРКЕР) and Path(дом).resolve() == КОРЕНЬ.resolve():
        raise RuntimeError("проба не пишет в боевой журнал — измерения "
                           "боевого дома рождаются только делом (tmp-дома)")
    for поле in ("задача", "выбор", "кто"):
        if not str(факт.get(поле, "")).strip():
            raise ValueError(f"факт без «{поле}» — брак в журнал не идёт")
    запись = dict(факт)
    варианты = [str(в) for в in (запись.get("из") or [])]
    if not варианты:
        варианты = [str(запись["выбор"])]
    if запись["выбор"] not in варианты:
        raise ValueError("выбор вне спектра — такого маршрута нет")
    запись["из"] = варианты
    запись["вариантов"] = len(варианты)
    запись["цена_с"] = round(float(запись.get("цена_с", 0.0)), 2)
    запись.setdefault("улика", "")
    запись["момент"] = datetime.now().strftime("%d.%m.%Y %H:%M")
    запись["номер"] = номер_факта(дом)
    хвост = _хэши_префиксов(_сырые_строки(дом))
    запись["предыдущий"] = хвост[-1] if хвост else БАЗА_ХЭШ
    запись["печать"] = _печать(запись)
    _дозапись(дом / ФАКТЫ_ФАЙЛ, json.dumps(запись, ensure_ascii=False) + "\n")
    return запись


def проверить_цепь(дом: Path | None = None) -> dict:
    """Проверка цепи хэшей журнала: каждая запечатанная запись обязана
    ссылаться на хэш всей предыдущей истории и совпадать со своей печатью.
    Допечатный хвост (записи до цепи) не ломает цепь — он накрыт хэшем
    истории: правка любой старой строки рвёт цепь следующей записи."""
    дом = Path(дом) if дом else КОРЕНЬ
    строки = _сырые_строки(дом)
    префиксы = _хэши_префиксов(строки)
    начало = БАЗА_ХЭШ
    разрывы: list[dict] = []
    запечатано = 0
    for и, с in enumerate(строки):
        з = json.loads(с)
        if not з.get("печать") or not з.get("предыдущий"):
            continue                        # допечатный хвост истории
        запечатано += 1
        ожидаемый = префиксы[и - 1] if и else начало
        номер = з.get("номер", и + 1)
        if з["предыдущий"] != ожидаемый:
            разрывы.append({"номер": номер, "что": "предыдущий хэш не сходится"})
        elif _печать(з) != з["печать"]:
            разрывы.append({"номер": номер, "что": "печать не сходится — запись подменена"})
    return {"фактов": len(строки), "запечатано": запечатано, "разрывы": разрывы,
            "вердикт": "цепь цела" if not разрывы else "цепь порвана"}


def печать_головы(дом: Path | None = None) -> str:
    """Печать головы цепи: якорь журнала для внешнего носителя (зерно,
    свидетель). Пустой журнал отдаёт печать базы — честный ноль истории."""
    дом = Path(дом) if дом else КОРЕНЬ
    хвост = _хэши_префиксов(_сырые_строки(дом))
    return хвост[-1] if хвост else БАЗА_ХЭШ


def _квантиль(цены: list[float], доля: float) -> float:
    """Хвост цены (ближайший ранг): p50/p95/p99 — среднее прячет бедствие
    одного шага, поэтому дом смотрит на хвост (мера мира, v108)."""
    if not цены:
        return 0.0
    и = max(0, math.ceil(доля * len(цены)) - 1)
    return round(float(цены[и]), 2)


def проекция(дом: Path | None = None) -> dict:
    """Проекция журнала: сводка дома выводится из фактов (по органам, по
    ценам — сумма и хвост p50/p95/p99), пишется в СВОДКА_ФАЙЛ целиком.
    Руками не правится: пересборка затирает рукопись (journal — источник
    истины, сводка — производное)."""
    дом = Path(дом) if дом else КОРЕНЬ
    записи = читать(дом)
    цены = sorted(float(з.get("цена_с", 0.0)) for з in записи)
    по_органам: dict[str, dict] = {}
    for з in записи:
        кто = str(з.get("кто", "неизвестно"))
        ячейка = по_органам.setdefault(кто, {"фактов": 0, "цена_с": 0.0})
        ячейка["фактов"] += 1
        ячейка["цена_с"] = round(ячейка["цена_с"]
                                 + float(з.get("цена_с", 0.0)), 2)
    цепь = проверить_цепь(дом)
    свод = {"фактов": len(записи), "органов": len(по_органам),
            "по_органам": по_органам,
            "цена_с": round(sum(цены), 2),
            "p50": _квантиль(цены, 0.50), "p95": _квантиль(цены, 0.95),
            "p99": _квантиль(цены, 0.99), "цепь": цепь,
            "последний": записи[-1] if записи else None,
            "сгенерировано": datetime.now().strftime("%d.%m.%Y %H:%M")}
    линии = [
        "# Проекция журнала фактов — сгенерировано, руками не править", "",
        f"- Собрано: {свод['сгенерировано']} из 32_SELFUPGRADE/факты.jsonl",
        f"- Фактов: {свод['фактов']} · органов: {свод['органов']}"
        f" · общая цена: {свод['цена_с']} с",
        f"- Хвост цены: p50 {свод['p50']} с · p95 {свод['p95']} с"
        f" · p99 {свод['p99']} с",
        f"- Цепь хэшей: {свод['цепь']['вердикт']}"
        f" (запечатано {свод['цепь']['запечатано']} из {свод['цепь']['фактов']})",
        "", "| орган | фактов | цена, с |", "|---|---|---|",
    ]
    for кто, я in sorted(по_органам.items(), key=lambda п: (-п[1]["фактов"], п[0])):
        линии.append(f"| {кто} | {я['фактов']} | {я['цена_с']} |")
    if записи:
        линии += ["", "## Последние измерения", ""]
        for з in записи[-5:][::-1]:
            линии.append(f"- №{з.get('номер')} {з.get('кто')}: "
                         f"{str(з.get('задача', ''))[:90]}"
                         f" → {str(з.get('выбор', ''))[:40]}"
                         f" ({з.get('цена_с', 0)} с)")
    линии.append("")
    путь = дом / СВОДКА_ФАЙЛ
    путь.parent.mkdir(parents=True, exist_ok=True)
    временный = путь.with_suffix(путь.suffix + ".tmp")
    временный.write_text("\n".join(линии), encoding="utf-8")
    os.replace(временный, путь)
    свод["файл"] = путь
    return свод


def читать(дом: Path | None = None) -> list[dict]:
    """Все факты журнала (сеть событий дома; без журнала — честный ноль)."""
    дом = Path(дом) if дом else КОРЕНЬ
    путь = дом / ФАКТЫ_ФАЙЛ
    if not путь.exists():
        return []
    return [json.loads(с) for с in
            путь.read_text(encoding="utf-8").splitlines() if с.strip()]


# ── Алгедонический канал (v111, Волна 4): боль мимо иерархии ──────────
def боль(что: str, кто: str, дом: Path | None = None, цена_с: float = 0.0,
         улика: str = "", ключ: str | None = None) -> dict:
    """Боль объявляется фактом высшим приоритетом — мимо шагов и очередей:
    стоп, карантин, дежурство, бой говорят прямо в журнал дома. Ключ —
    тождество боли (одна и та же боль не множится, растёт счётчик)."""
    маршруты = ["боль открыта", "боль не подтверждена"]
    запись = записать_факт(дом, {
        "задача": f"боль: {что}"[:200], "выбор": маршруты[0], "из": маршруты,
        "кто": str(кто), "цена_с": цена_с,
        "обоснование": "VSM: боль обязана долетать до верха, не тонуть в шагах",
        "улика": улика or "боль дома", "боль": True, "статус": "открыта",
        "ключ": str(ключ or что)[:120]})
    return запись


def залечить(ключ: str, чем: str = "", дом: Path | None = None,
             кто: str = "дом") -> dict:
    """Лечение боли — тоже факт: открытая боль закрывается записью-лечением
    (журнал первичен: ничто не стирается, история боли остаётся)."""
    маршруты = ["боль залечена", "лечение не принято"]
    return записать_факт(дом, {
        "задача": f"лечение боли {ключ}: {чем}"[:200], "выбор": маршруты[0],
        "из": маршруты, "кто": str(кто), "цена_с": 0.0,
        "обоснование": "лечение закрывает боль фактом, а не тишиной",
        "улика": "лечение боли", "боль": True, "статус": "залечена",
        "ключ": str(ключ)[:120]})


def боли(дом: Path | None = None) -> list[dict]:
    """Открытые боли дома: по каждому ключу смотрим последнюю запись —
    открыта она или залечена; счётчик записей честно показывает, сколько
    раз боль кричала. Порядок — как кричали (номер факта)."""
    дом = Path(дом) if дом else КОРЕНЬ
    по_ключу: dict[str, dict] = {}
    for з in читать(дом):
        if not з.get("боль"):
            continue
        ключ = str(з.get("ключ", ""))
        ячейка = по_ключу.setdefault(ключ, {"записей": 0, "статус": "",
                                            "номер": 0, "что": "",
                                            "кто": "", "момент": ""})
        ячейка["записей"] += 1
        ячейка["статус"] = з.get("статус", "")
        ячейка["номер"] = з.get("номер", 0)
        ячейка["что"] = з.get("задача", "")
        ячейка["кто"] = з.get("кто", "")
        ячейка["момент"] = з.get("момент", "")
    открытые = [dict(ключ=к, **я) for к, я in по_ключу.items()
                if я["статус"] == "открыта"]
    return sorted(открытые, key=lambda б: б["номер"])


